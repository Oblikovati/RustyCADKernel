//! `AppCont_ContMatrices`: the precomputed Bernstein matrices of the continuous
//! least-squares fit — the mass matrix, its inverse, the constrained normal-matrix
//! inverses and the basis values at the Gauss points — read from the verbatim native
//! tables (generated by tools/generate_appcont_tables.py).
use crate::native_failure::failure;
use rustycad_tkernel::standard::Failure;
use rustycad_tkmath::math::Matrix;

pub use super::cont_tables::{
    ContMatrixTable, THE_BBMATRIX_DATA, THE_IBPMATRIX_DATA, THE_IBTMATRIX_DATA,
    THE_INV_MMATRIX_DATA, THE_VBMATRIX_DATA,
};

/// `THE_MAX_CLASSE`: the largest classe of IBPMatrix, IBTMatrix and VBernstein.
pub const THE_MAX_CLASSE: i32 = 26;
/// `THE_MAX_MMATRIX_CLASSE`: the largest classe of MMatrix and InvMMatrix.
pub const THE_MAX_MMATRIX_CLASSE: i32 = 24;
/// `THE_MAX_NBPOINTS`: the largest number of Gauss points of VBernstein.
pub const THE_MAX_NBPOINTS: i32 = 24;

/// `MMatrixOffset(theClasse)`: the start of the classe block in the flat
/// MMatrix/InvMMatrix arrays (blocks of `i * i` entries from classe 2);
/// `m_matrix_offset(4) == 13`.
pub const fn m_matrix_offset(the_classe: i32) -> i32 {
    squares_below(2, the_classe)
}

/// `IBPMatrixOffset(theClasse)`: the start of the classe block in the flat IBPMatrix
/// array (blocks of `(classe - 2)^2` entries from classe 3); `ibp_matrix_offset(5) == 5`.
pub const fn ibp_matrix_offset(the_classe: i32) -> i32 {
    squares_below(1, the_classe.saturating_sub(2))
}

/// `IBTMatrixOffset(theClasse)`: the start of the classe block in the flat IBTMatrix
/// array (blocks of `(classe - 4)^2` entries from classe 5); `ibt_matrix_offset(7) == 5`.
pub const fn ibt_matrix_offset(the_classe: i32) -> i32 {
    squares_below(1, the_classe.saturating_sub(4))
}

// `sum(i * i)` for `first <= i < end`, the loop the three offset functions share. The
// native `int` sum overflows (undefined behavior) past classe 1861; the port wraps.
const fn squares_below(first: i32, end: i32) -> i32 {
    let mut offset: i32 = 0;
    let mut i: i32 = first;
    while i < end {
        offset = offset.wrapping_add(i.wrapping_mul(i));
        i += 1;
    }
    offset
}

// The Standard_DimensionError the matrix providers raise past their stored classes.
fn dimension_error(member: &str, value: i32, limit: i32, what: &str) -> Failure {
    failure(
        "Standard_DimensionError",
        &format!("{member}: {what} = {value}; expected {what} <= {limit}"),
    )
}

// A block of `rows x cols` table entries, row-major from `offset`, written at
// `origin + (i - 1, j - 1)`. A read past the native array (undefined behavior natively)
// is Standard_OutOfRange; a cell outside the matrix is the Standard_OutOfRange of
// `math_Matrix::operator()`.
fn fill_block(
    table: &ContMatrixTable,
    offset: i64,
    [rows, cols]: [i32; 2],
    matrix: &mut Matrix<'_>,
    [row0, col0]: [i32; 2],
) -> Result<(), Failure> {
    let mut k: i64 = offset;
    for i in 1..=rows {
        for j in 1..=cols {
            *matrix.change_value(i + row0 - 1, j + col0 - 1)? = table_entry(table, k)?;
            k += 1;
        }
    }
    Ok(())
}

// The flat entry `index` of `table`, Standard_OutOfRange outside the native array.
fn table_entry(table: &ContMatrixTable, index: i64) -> Result<f64, Failure> {
    usize::try_from(index)
        .ok()
        .and_then(|position| table.get(position))
        .ok_or_else(|| {
            Failure::out_of_range(&format!(
                "AppCont_ContMatrices: table index {index}; expected 0..{}",
                table.len()
            ))
        })
}

// The lower corner of `matrix`, where the square providers start writing.
fn lower_corner(matrix: &Matrix<'_>) -> [i32; 2] {
    [matrix.lower_row(), matrix.lower_col()]
}

/// `MMatrix(classe, M)`: the Bernstein mass matrix of size `classe x classe`, written
/// from the lower corner of `m`; Standard_DimensionError for classe > 24.
///
/// ```
/// use rustycad_tkgeombase::app_cont::cont_matrices::m_matrix;
/// use rustycad_tkmath::math::Matrix;
/// let mut m = Matrix::with_bounds(1, 2, 1, 2)?;
/// m_matrix(2, &mut m)?;
/// assert_eq!(m[(1, 2)], 0.1666666666666666666666667);
/// # Ok::<(), Box<dyn std::error::Error>>(())
/// ```
pub fn m_matrix(classe: i32, m: &mut Matrix<'_>) -> Result<(), Failure> {
    if classe > THE_MAX_MMATRIX_CLASSE {
        return Err(dimension_error("MMatrix", classe, 24, "classe"));
    }
    let offset: i64 = m_matrix_offset(classe).into();
    let corner: [i32; 2] = lower_corner(m);
    fill_block(&THE_BBMATRIX_DATA, offset, [classe, classe], m, corner)
}

/// `InvMMatrix(classe, InvM)`: the inverse of the mass matrix;
/// Standard_DimensionError for classe > 24; `inv_m_matrix(4, &mut inv)?`.
pub fn inv_m_matrix(classe: i32, inv_m: &mut Matrix<'_>) -> Result<(), Failure> {
    if classe > THE_MAX_MMATRIX_CLASSE {
        return Err(dimension_error("InvMMatrix", classe, 24, "classe"));
    }
    let offset: i64 = m_matrix_offset(classe).into();
    let corner: [i32; 2] = lower_corner(inv_m);
    fill_block(
        &THE_INV_MMATRIX_DATA,
        offset,
        [classe, classe],
        inv_m,
        corner,
    )
}

/// `IBPMatrix(classe, IBPMa)`: the inverse of `MP^T MP` for pass-point constraints
/// (MP the columns `2..classe-1` of M), `(classe-2) x (classe-2)`;
/// Standard_DimensionError for classe > 26; `ibp_matrix(5, &mut ibp)?`.
pub fn ibp_matrix(classe: i32, ibp_ma: &mut Matrix<'_>) -> Result<(), Failure> {
    if classe > THE_MAX_CLASSE {
        return Err(dimension_error("IBPMatrix", classe, 26, "classe"));
    }
    let offset: i64 = ibp_matrix_offset(classe).into();
    let corner: [i32; 2] = lower_corner(ibp_ma);
    let dim: i32 = classe.saturating_sub(2);
    fill_block(&THE_IBPMATRIX_DATA, offset, [dim, dim], ibp_ma, corner)
}

/// `IBTMatrix(classe, IBTMa)`: the inverse of `MT^T MT` for tangency constraints
/// (MT the columns `3..classe-2` of M), `(classe-4) x (classe-4)`;
/// Standard_DimensionError for classe > 26; `ibt_matrix(7, &mut ibt)?`.
pub fn ibt_matrix(classe: i32, ibt_ma: &mut Matrix<'_>) -> Result<(), Failure> {
    if classe > THE_MAX_CLASSE {
        return Err(dimension_error("IBTMatrix", classe, 26, "classe"));
    }
    let offset: i64 = ibt_matrix_offset(classe).into();
    let corner: [i32; 2] = lower_corner(ibt_ma);
    let dim: i32 = classe.saturating_sub(4);
    fill_block(&THE_IBTMATRIX_DATA, offset, [dim, dim], ibt_ma, corner)
}

/// `VBernstein(classe, nbpoints, M)`: the `classe` Bernstein polynomials at the
/// `nbpoints` Gauss points of [0, 1], `classe x nbpoints`, written at `M(1, 1)` whatever
/// the bounds of `m` (unlike the other providers); Standard_DimensionError for
/// classe > 26 or nbpoints > 24.
///
/// Classe 1 addresses the table before its start (undefined behavior natively): the
/// port raises Standard_OutOfRange there.
///
/// ```
/// use rustycad_tkgeombase::app_cont::cont_matrices::v_bernstein;
/// use rustycad_tkmath::math::Matrix;
/// let mut vb = Matrix::with_bounds(1, 3, 1, 4)?;
/// v_bernstein(3, 4, &mut vb)?;
/// assert!((vb[(1, 1)] + vb[(2, 1)] + vb[(3, 1)] - 1.0).abs() < 1e-15);
/// # Ok::<(), Box<dyn std::error::Error>>(())
/// ```
pub fn v_bernstein(classe: i32, nbpoints: i32, m: &mut Matrix<'_>) -> Result<(), Failure> {
    if classe > THE_MAX_CLASSE {
        return Err(dimension_error("VBernstein", classe, 26, "classe"));
    }
    if nbpoints > THE_MAX_NBPOINTS {
        return Err(dimension_error("VBernstein", nbpoints, 24, "nbpoints"));
    }
    if classe < 1 || nbpoints < 1 {
        // The native loops read nothing then, whatever the offset.
        return Ok(());
    }
    fill_block(
        &THE_VBMATRIX_DATA,
        v_bernstein_offset(classe, nbpoints),
        [classe, nbpoints],
        m,
        [1, 1],
    )
}

// `Som`: the native offset, computed in double and truncated toward zero as the
// `static_cast<int>` does.
fn v_bernstein_offset(classe: i32, nbpoints: i32) -> i64 {
    let triangle: f64 = f64::from((classe - 1) * classe) / 2.0;
    let som: f64 = 300.0 * (triangle - 1.0) + f64::from(classe * (nbpoints - 1) * nbpoints) / 2.0;
    som as i64
}
