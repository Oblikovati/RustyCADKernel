#!/usr/bin/env python3
"""Carry the AppCont_ContMatrices tables over from the pinned OCCT sources verbatim.

Usage: python3 tools/generate_appcont_tables.py --source ../OCCT [--check]

AppCont_ContMatrices_{BB,InvM,IBP,IBT,VB}.pxx hold five flat `static const double`
arrays (125k literals). Every literal is copied as text, so rustc rounds exactly the
decimal strings g++ rounds; the three IBP entries written as `a - b` stay constant
expressions, which both compilers fold in IEEE double arithmetic. The arrays are split
into include!-able fragments of CHUNK values (under 500 lines each) under
crates/tkgeombase/src/app_cont/cont_tables/, indexed by cont_tables.rs. `--check`
regenerates everything in memory and fails on any difference.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT/'crates/tkgeombase/src/app_cont'
PACKAGE = 'src/ModelingData/TKGeomBase/AppCont'
PER_LINE = 4
CHUNK = 480*PER_LINE
ARRAY = re.compile(r'static\s+const\s+double\s+(\w+)\s*\[\s*\]\s*=\s*\{(.*?)\};', re.S)
LITERAL = r'[-+]?\d+\.\d*(?:[eE][-+]?\d+)?'
TOKEN = re.compile(rf'{LITERAL}(?: - {LITERAL})?')
# (native array, header, expected literal count): the classe 2..26 (BB, InvM),
# 3..26 (IBP), 5..26 (IBT) and classe x nbpoints 2..26 x 1..24 (VB) blocks.
TABLES = [
    ('THE_BBMATRIX_DATA', 'AppCont_ContMatrices_BB.pxx', sum(i*i for i in range(2, 27))),
    ('THE_INV_MMATRIX_DATA', 'AppCont_ContMatrices_InvM.pxx', sum(i*i for i in range(2, 27))),
    ('THE_IBPMATRIX_DATA', 'AppCont_ContMatrices_IBP.pxx', sum(i*i for i in range(1, 25))),
    ('THE_IBTMATRIX_DATA', 'AppCont_ContMatrices_IBT.pxx', sum(i*i for i in range(1, 23))),
    ('THE_VBMATRIX_DATA', 'AppCont_ContMatrices_VB.pxx', sum(c*n for c in range(2, 27) for n in range(1, 25))),
]


def parse_table(text: str, name: str) -> list[str]:
    """The literal strings of one array, comments dropped; parse_table(pxx_text, 'THE_BBMATRIX_DATA')."""
    stripped = re.sub(r'//[^\n]*', ' ', re.sub(r'/\*.*?\*/', ' ', text, flags=re.S))
    bodies = {found: body for found, body in ARRAY.findall(stripped)}
    if name not in bodies: raise ValueError(f'{name} not found; expected `static const double {name}[] = {{...}};`')
    values = [token.strip() for token in bodies[name].split(',') if token.strip()]
    for value in values:
        if not TOKEN.fullmatch(value):
            raise ValueError(f'{name}: literal {value!r}; expected a decimal double or `a - b` of two')
    return values


def rust_name(name: str) -> str:
    """The fragment stem of a native array; rust_name('THE_INV_MMATRIX_DATA') == 'inv_mmatrix'."""
    return name.removeprefix('THE_').removesuffix('_DATA').lower()


def fragments(name: str, values: list[str]) -> dict[str, str]:
    """Split one table into include!-able slice fragments; fragments('THE_X_DATA', values)."""
    files = {}
    for index in range(0, len(values), CHUNK):
        chunk = values[index:index+CHUNK]
        rows = [', '.join(chunk[row:row+PER_LINE]) for row in range(0, len(chunk), PER_LINE)]
        body = ''.join(f'    {row},\n' for row in rows)
        files[f'{rust_name(name)}_{index//CHUNK}.rs'] = f'&[\n{body}]\n'
    return files


def chunk_order(file: str) -> tuple[str, int]:
    """Sort fragments by table then numeric chunk; chunk_order('vbmatrix_10.rs') == ('vbmatrix', 10)."""
    stem, index = file[:-3].rsplit('_', 1)
    return stem, int(index)


INDEX_PRELUDE = '''//! AppCont_ContMatrices tables generated by tools/generate_appcont_tables.py; do not edit.
//!
//! The literals come verbatim from AppCont_ContMatrices_{BB,InvM,IBP,IBT,VB}.pxx at
//! 3d097a0328e71b826377d4814ab05ec3c3d23871, split into fragments of at most
//! '''+str(CHUNK)+''' values.
#![allow(clippy::excessive_precision)]

/// One flat native `static const double` array, stored as fixed-size fragments.
///
/// ```
/// use rustycad_tkgeombase::app_cont::cont_matrices::THE_BBMATRIX_DATA;
/// assert_eq!(THE_BBMATRIX_DATA.get(0), Some(0.3333333333333333333333333));
/// assert_eq!(THE_BBMATRIX_DATA.get(THE_BBMATRIX_DATA.len()), None);
/// ```
pub struct ContMatrixTable {
    chunks: &'static [&'static [f64]],
}
impl ContMatrixTable {
    /// The flattened entry `index`, or `None` past the native array end;
    /// `THE_BBMATRIX_DATA.get(0)`.
    pub fn get(&self, index: usize) -> Option<f64> {
        self.chunks.get(index / CHUNK)?.get(index % CHUNK).copied()
    }
    /// The number of entries of the native array; `THE_BBMATRIX_DATA.len()`.
    pub fn len(&self) -> usize {
        self.chunks.iter().map(|chunk| chunk.len()).sum()
    }
    /// Whether the array has no entry (never, for the native tables);
    /// `THE_BBMATRIX_DATA.is_empty()`.
    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }
}
const CHUNK: usize = '''+str(CHUNK)+''';
'''


def index_module(tables: dict[str, tuple[str, list[str]]], files: dict[str, str]) -> str:
    """The constant index over the fragments; index_module({name: (header, values)}, files)."""
    lines = [INDEX_PRELUDE]
    for name, (header, values) in tables.items():
        stem = rust_name(name)
        includes = ''.join(f'        include!("cont_tables/{file}"),\n'
                           for file in sorted(files, key=chunk_order) if chunk_order(file)[0] == stem)
        lines.append(f'/// `AppCont_ContMatrices::{name}` from `{header}` ({len(values)} values).\n'
                     f'pub const {name}: ContMatrixTable = ContMatrixTable {{\n'
                     f'    chunks: &[\n{includes}    ],\n}};\n')
    return '\n'.join(lines)


def generate(source: Path) -> dict[Path, str]:
    """Render every generated file keyed by its repository path; generate(Path('../OCCT'))."""
    tables: dict[str, tuple[str, list[str]]] = {}
    files: dict[str, str] = {}
    for name, header, expected in TABLES:
        text = (source/PACKAGE/header).read_text()
        values = parse_table(text, name)
        if len(values) != expected:
            raise ValueError(f'{header}:{name} has {len(values)} literals; expected {expected}')
        tables[name] = (header, values)
        files.update(fragments(name, values))
    output = {TARGET/'cont_tables'/file: text for file, text in files.items()}
    output[TARGET/'cont_tables.rs'] = index_module(tables, files)
    return output


def main() -> int:
    """Write or check the generated tables; exit 1 when --check finds drift."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT/'../OCCT')
    parser.add_argument('--check', action='store_true', help='fail when a generated file differs')
    arguments = parser.parse_args()
    output = generate(arguments.source.resolve())
    stale = [path for path, text in output.items() if not path.exists() or path.read_text() != text]
    existing = set((TARGET/'cont_tables').glob('*.rs'))
    orphans = sorted(existing - set(output))
    if arguments.check:
        for path in stale+orphans: print(f'stale generated table: {path.relative_to(ROOT)}')
        return 1 if stale or orphans else 0
    (TARGET/'cont_tables').mkdir(parents=True, exist_ok=True)
    for path in stale: path.write_text(output[path])
    for path in orphans: path.unlink()
    print(f'{len(output)} files, {len(stale)} written, {len(orphans)} removed')
    return 0


if __name__ == '__main__':
    sys.exit(main())
