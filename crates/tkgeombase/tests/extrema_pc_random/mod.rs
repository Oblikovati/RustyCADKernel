//! The `std::mt19937` / `std::uniform_real_distribution` points of the ExtremaPC
//! comparison suites, as the pinned libstdc++ build draws them (with its argument
//! evaluation order in `gp_Pnt(aDist(aGen), ...)`); generated by
//! tools/oracle/tkgeombase_extrema_random_points.cxx.
use rustycad_tkmath::gp::Point3;

const POINTS: &str = include_str!("../fixtures/extrema_pc_random_points.txt");

/// The points of one fixture family, in draw order.
pub fn random_points(name: &str) -> Vec<Point3> {
    POINTS
        .lines()
        .filter_map(|line| {
            let mut fields = line.split_whitespace();
            if fields.next() != Some(name) {
                return None;
            }
            let values: Vec<f64> = fields.map(|v| v.parse().unwrap()).collect();
            Some(Point3::new(values[0], values[1], values[2]))
        })
        .collect()
}
