/// Bounds the error of dropping the coefficients past `ncfnew` of a Jacobi curve of
/// continuity order `iordre` (`mmaperx_`): `ycvmax` receives the bound per dimension
/// and `errmax` its norm. `iercod` is 1 for an order outside -1..=2; returns 0.
/// `mmaperx_(6, 3, 6, 0, &crvjac, 3, &mut ycvmax, &mut errmax, &mut iercod)`.
pub fn mmaperx_(
    ncofmx: i32,
    ndimen: i32,
    ncoeff: i32,
    iordre: i32,
    crvjac: &[f64],
    ncfnew: i32,
    ycvmax: &mut [f64],
    errmax: &mut f64,
    iercod: &mut i32,
) -> i32 {
    *iercod = 0;
    let curve = TruncatedCurve {
        ncofmx,
        ndimen,
        ncoeff,
        coefficients: crvjac,
        ncfnew,
    };
    match (iordre + 1) << 1 {
        0 => mmaper0_(&curve, ycvmax, errmax),
        2 => mmaperj_(&curve, 3, &XMAXJ_ORDER2, ycvmax, errmax),
        4 => mmaperj_(&curve, 5, &XMAXJ_ORDER4, ycvmax, errmax),
        6 => mmaperj_(&curve, 7, &XMAXJ_ORDER6, ycvmax, errmax),
        _ => *iercod = 1,
    }
    0
}

/// The curve arguments shared by the `mmaper*_` routines: `(ncofmx, ndimen)`
/// coefficients of which the first `ncoeff` are used and the first `ncfnew` kept.
struct TruncatedCurve<'a> {
    ncofmx: i32,
    ndimen: i32,
    ncoeff: i32,
    coefficients: &'a [f64],
    ncfnew: i32,
}

/// `mmaper0_`: the bound for a Legendre curve, whose basis maxima are
/// `sqrt((2k+1)/2)`.
fn mmaper0_(curve: &TruncatedCurve<'_>, ycvmax: &mut [f64], errmax: &mut f64) {
    let dim1: i32 = curve.ncofmx;
    let crvlgd = F2cArray::new(curve.coefficients, dim1 + 1);
    let mut ycv = F2cArrayMut::new(ycvmax, 1);
    for ii in 1..=curve.ndimen {
        ycv[ii] = 0.;
    }
    let mut ncut: i32 = 1;
    if curve.ncfnew >= ncut {
        ncut = curve.ncfnew + 1;
    }
    for ii in ncut..=curve.ncoeff {
        let mut bidon: f64 = (f64::from(ii - 1) * 2. + 1.) / 2.;
        bidon = bidon.sqrt();
        for nd in 1..=curve.ndimen {
            ycv[nd] += crvlgd[ii + nd * dim1].abs() * bidon;
        }
    }
    *errmax = mzsnorm_(curve.ndimen, ycv.tail(1));
}

/// `mmaper2_`, `mmaper4_` and `mmaper6_`: the bound for a Jacobi curve whose basis
/// maxima start at degree `idec` in `xmaxj`.
fn mmaperj_(
    curve: &TruncatedCurve<'_>,
    idec: i32,
    xmaxj: &[f64],
    ycvmax: &mut [f64],
    errmax: &mut f64,
) {
    let dim1: i32 = curve.ncofmx;
    let crvjac = F2cArray::new(curve.coefficients, dim1 + 1);
    let mut ycv = F2cArrayMut::new(ycvmax, 1);
    for ii in 1..=curve.ndimen {
        ycv[ii] = 0.;
    }
    let ncut: i32 = idec.max(curve.ncfnew + 1);
    for ii in ncut..=curve.ncoeff {
        let bidon: f64 = xmaxj[(ii - idec) as usize];
        for nd in 1..=curve.ndimen {
            ycv[nd] += crvjac[ii + nd * dim1].abs() * bidon;
        }
    }
    *errmax = mzsnorm_(curve.ndimen, ycv.tail(1));
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn legendre_bound_sums_the_dropped_coefficients() {
        let crvjac: [f64; 3] = [1.0, -0.5, 0.25];
        let (mut ycvmax, mut errmax, mut iercod) = ([0.0; 1], 0.0, 9);
        mmaperx_(
            3,
            1,
            3,
            -1,
            &crvjac,
            1,
            &mut ycvmax,
            &mut errmax,
            &mut iercod,
        );
        let expected: f64 = 0.5 * 1.5f64.sqrt() + 0.25 * 2.5f64.sqrt();
        assert_eq!((iercod, ycvmax[0], errmax), (0, expected, expected));
    }

    #[test]
    fn jacobi_bounds_use_the_shared_maxima_and_refuse_high_orders() {
        let crvjac: [f64; 4] = [0.0, 0.0, 0.0, 2.0];
        let (mut ycvmax, mut errmax, mut iercod) = ([0.0; 1], 0.0, 0);
        mmaperx_(
            4,
            1,
            4,
            0,
            &crvjac,
            2,
            &mut ycvmax,
            &mut errmax,
            &mut iercod,
        );
        assert_eq!(ycvmax[0], 2.0 * XMAXJ_ORDER2[1]);
        mmaperx_(
            4,
            1,
            4,
            3,
            &crvjac,
            2,
            &mut ycvmax,
            &mut errmax,
            &mut iercod,
        );
        assert_eq!(iercod, 1);
    }
}
