/// The shapes generated from a sub-shape of the profile, by profile shape.
pub type ProfileGenerated = DataMap<Shape, List<Shape>, ShapeMapHasher>;
/// The generated shapes by spine shape and profile shape (`myMap`).
pub type EvolvedMap = DataMap<Shape, ProfileGenerated, ShapeMapHasher>;
/// A map of shapes to shapes (cut parts to their origin).
pub type ShapeOrigins = DataMap<Shape, Shape, ShapeMapHasher>;

/// The evolved shape of a spine and a profile (`BRepFill_Evolved`); natively the spine
/// type and join type are uninitialized until Perform (true and Arc here);
/// `let evo = BRepFillEvolved::from_wire(&spine, &profile, &axe, JoinType::Arc, false)?;`.
#[derive(Clone)]
pub struct BRepFillEvolved {
    my_spine: Face,
    my_profile: Wire,
    my_shape: Shape,
    my_is_done: bool,
    my_spine_type: bool,
    my_join_type: JoinType,
    my_map: EvolvedMap,
    my_top: Shape,
    my_bottom: Shape,
    /// The empty list GeneratedShapes returns (a function static natively).
    my_empty: List<Shape>,
}

impl Default for BRepFillEvolved {
    /// `BRepFill_Evolved()`: not done, face spine.
    fn default() -> Self {
        Self {
            my_spine: Face::default(),
            my_profile: Wire::default(),
            my_shape: Shape::default(),
            my_is_done: false,
            my_spine_type: true,
            my_join_type: JoinType::Arc,
            my_map: EvolvedMap::default(),
            my_top: Shape::default(),
            my_bottom: Shape::default(),
            my_empty: List::default(),
        }
    }
}

/// Standard_NoSuchObject of a missing generated shape (a DataMap Find natively).
pub(crate) fn no_such(what: &str) -> Failure {
    Failure::with_type(
        "Standard_NoSuchObject",
        &format!("BRepFill_Evolved: {what}; expected a bound key"),
        "BRepFill_Evolved",
    )
}

/// `myMap(a)(b)`: the generated shapes of the spine shape `a` and profile shape `b`.
pub(crate) fn find2<'m>(
    map: &'m EvolvedMap,
    a: &Shape,
    b: &Shape,
) -> Result<&'m List<Shape>, Failure> {
    map.seek(a)
        .and_then(|m| m.seek(b))
        .ok_or_else(|| no_such("no shapes generated by this spine and profile shape"))
}

/// `myMap(a)(b)` changed.
pub(crate) fn find2_mut<'m>(
    map: &'m mut EvolvedMap,
    a: &Shape,
    b: &Shape,
) -> Result<&'m mut List<Shape>, Failure> {
    map.change_seek(a)
        .and_then(|m| m.change_seek(b))
        .ok_or_else(|| no_such("no shapes generated by this spine and profile shape"))
}

/// The first shape of a list (Standard_NoSuchObject when empty).
pub(crate) fn first_of(l: &List<Shape>) -> Result<Shape, Failure> {
    l.first()
        .cloned()
        .ok_or_else(|| no_such("an empty list of generated shapes"))
}

impl BRepFillEvolved {
    /// `BRepFill_Evolved()`; `BRepFillEvolved::new()`.
    pub fn new() -> Self {
        Self::default()
    }

    /// `BRepFill_Evolved(Spine, Profile, AxeProf, Join, Solid)` with a wire spine
    /// (Join natively defaulted to Arc, Solid to false);
    /// `BRepFillEvolved::from_wire(&spine, &profile, &axe, JoinType::Arc, false)?`.
    pub fn from_wire(
        spine: &Wire,
        profile: &Wire,
        axe_prof: &Axis3,
        join: JoinType,
        solid: bool,
    ) -> Result<Self, Failure> {
        let mut evo = Self::new();
        evo.perform_wire(spine, profile, axe_prof, join, solid)?;
        Ok(evo)
    }

    /// `BRepFill_Evolved(Spine, Profile, AxeProf, Join, Solid)` with a face spine;
    /// `BRepFillEvolved::from_face(&spine, &profile, &axe, JoinType::Arc, false)?`.
    pub fn from_face(
        spine: &Face,
        profile: &Wire,
        axe_prof: &Axis3,
        join: JoinType,
        solid: bool,
    ) -> Result<Self, Failure> {
        let mut evo = Self::new();
        evo.perform_face(spine, profile, axe_prof, join, solid)?;
        Ok(evo)
    }

    /// `Perform(Spine, Profile, AxeProf, Join, Solid)` with a wire spine: on its planar
    /// face; `evo.perform_wire(&spine, &profile, &axe, JoinType::Arc, false)?`.
    pub fn perform_wire(
        &mut self,
        spine: &Wire,
        profile: &Wire,
        axe_prof: &Axis3,
        join: JoinType,
        solid: bool,
    ) -> Result<(), Failure> {
        self.my_spine_type = false;
        let a_face = BRepLibMakeFace::from_wire(spine, true)?.face()?;
        self.private_perform(&a_face, profile, axe_prof, join, solid)
    }

    /// `Perform(Spine, Profile, AxeProf, Join, Solid)` with a face spine;
    /// `evo.perform_face(&spine, &profile, &axe, JoinType::Arc, false)?`.
    pub fn perform_face(
        &mut self,
        spine: &Face,
        profile: &Wire,
        axe_prof: &Axis3,
        join: JoinType,
        solid: bool,
    ) -> Result<(), Failure> {
        self.my_spine_type = true;
        self.private_perform(spine, profile, axe_prof, join, solid)
    }

    /// The left and right presence of the profile parts.
    fn sides_present(work_prof: &List<Shape>) -> Result<(bool, bool), Failure> {
        let (mut ya_left, mut ya_right) = (false, false);
        for sp in work_prof.iter() {
            if side(&topods::wire(sp)?, confusion())? < 4 {
                ya_left = true;
            } else {
                ya_right = true;
            }
            if ya_left && ya_right {
                break;
            }
        }
        Ok((ya_left, ya_right))
    }

    /// The wire of all the edges of the profile parts.
    fn whole_profile(work_prof: &List<Shape>) -> Result<Wire, Failure> {
        let bb = rustycad_tkbrep::brep::BRepBuilder::default();
        let mut wp = Wire::default();
        bb.make_wire(&mut wp);
        let mut wp_shape = wp.into_shape();
        for w in work_prof.iter() {
            let mut wexp = WireExplorer::with_wire(&topods::wire(w)?)?;
            while wexp.more() {
                bb.add(&mut wp_shape, wexp.current().as_ref())?;
                wexp.next()?;
            }
        }
        topods::wire(&wp_shape)
    }

    /// The elementary volevo of each profile part on the side `sides` (1..=3 left,
    /// 4..=6 right) added to `cut_vevo`, on the face `face` with its locus.
    fn add_side_vevos(
        &self,
        face: &Face,
        work_prof: &List<Shape>,
        sides: i32,
        join: JoinType,
        cut_vevo: &mut Self,
        glue: &mut Quilt,
    ) -> Result<(), Failure> {
        let mut exp = BRepMAT2dExplorer::new();
        exp.perform(face)?;
        let mut locus = BRepMAT2dBisectingLocus::new();
        locus.compute(&mut exp, 1, MatSide::Left, JoinType::Arc, false)?;
        let mut link = BRepMAT2dLinkTopoBilo::with_locus(&exp, &locus)?;
        for sp in work_prof.iter() {
            let sp = topods::wire(sp)?;
            let c_side = side(&sp, confusion())?;
            let mut vevo = Self::new();
            match c_side - sides {
                0 => vevo.elementary_perform(face, &sp, &locus, &mut link, join)?,
                1 => vevo.planar_perform(face, &sp, &locus, &mut link, join)?,
                2 => vevo.vertical_perform(face, &sp, &locus, &mut link, join)?,
                _ => {}
            }
            cut_vevo.add(&mut vevo, &sp, glue)?;
        }
        Ok(())
    }

    /// The volevos to the right: per wire of the spine, on the plane face of the
    /// reversed wire.
    fn add_right_vevos(
        &self,
        work_spine: &Face,
        work_prof: &List<Shape>,
        join: JoinType,
        cut_vevo: &mut Self,
        glue: &mut Quilt,
    ) -> Result<(), Failure> {
        for w in Explorer::new(work_spine.as_ref(), ShapeEnum::Wire, ShapeEnum::Shape)? {
            let mut b = BRepLibMakeFace::from_plane(Plane3::from_equation(0., 0., 1., 0.)?)?;
            b.add(&topods::wire(&w.reversed())?)?;
            let face = b.face()?;
            self.add_side_vevos(&face, work_prof, 4, join, cut_vevo, glue)?;
        }
        Ok(())
    }

    /// `PrivatePerform(Spine, Profile, AxeProf, Join, Solid)` (private): the spine and the
    /// profile set in the work space, prepared, swept per part and side, glued, then
    /// transferred back; Standard_NotImplemented for a join other than Arc.
    fn private_perform(
        &mut self,
        spine: &Face,
        profile: &Wire,
        axe_prof: &Axis3,
        join: JoinType,
        solid: bool,
    ) -> Result<(), Failure> {
        self.my_spine = topods::face(&spine.as_ref().oriented(Orientation::Forward))?;
        self.my_profile = topods::wire(&profile.as_ref().oriented(Orientation::Forward))?;
        self.my_join_type = join;
        self.my_map.clear(false);
        if join != JoinType::Arc {
            return Err(Failure::with_type(
                "Standard_NotImplemented",
                &format!("BRepFill_Evolved: join type {join:?}; expected Arc"),
                "BRepFill_Evolved",
            ));
        }
        let l_spine = self.find_location(&self.my_spine)?;
        let mut t = Transform3::default();
        t.set_transformation_to(*axe_prof);
        let l_profile = Location::new(t);
        let (init_ls, init_lp) = (
            self.my_spine.as_ref().location().clone(),
            self.my_profile.as_ref().location().clone(),
        );
        self.transform_init_work(&l_spine, &l_profile)?;
        let (mut work_prof, mut map_prof) = (List::default(), ShapeOrigins::default());
        self.prepare_profile(&mut work_prof, &mut map_prof)?;
        let (mut work_spine, mut map_spine) = (Face::default(), ShapeOrigins::default());
        self.prepare_spine(&mut work_spine, &mut map_spine)?;
        let (ya_left, ya_right) = Self::sides_present(&work_prof)?;
        let mut cut_vevo = Self::new();
        cut_vevo.set_work(&work_spine, &Self::whole_profile(&work_prof)?);
        let mut glue = Quilt::new();
        if ya_left {
            self.add_side_vevos(&work_spine, &work_prof, 1, join, &mut cut_vevo, &mut glue)?;
        }
        if ya_right {
            self.add_right_vevos(&work_spine, &work_prof, join, &mut cut_vevo, &mut glue)?;
        }
        if solid {
            cut_vevo.add_top_and_bottom(&mut glue)?;
        }
        cut_vevo.continuity_on_offset_edge(&work_prof)?;
        *cut_vevo.change_shape() = glue.shells()?;
        self.transfert(
            &mut cut_vevo,
            &map_prof,
            &map_spine,
            &l_spine.inverted()?,
            &init_ls,
            &init_lp,
        )?;
        if solid {
            self.make_solid()?;
        }
        brep_lib::update_tolerances(&self.my_shape, false)?;
        self.my_is_done = true;
        Ok(())
    }

    /// `SetWork(Spine, Profile)` (private): the spine and profile as they are.
    fn set_work(&mut self, sp: &Face, pr: &Wire) {
        self.my_spine = sp.clone();
        self.my_profile = pr.clone();
    }

    /// `IsDone()`; `evo.is_done()`.
    pub fn is_done(&self) -> bool {
        self.my_is_done
    }

    /// `Shape()`: the evolved shape; `evo.shape()`.
    pub fn shape(&self) -> &Shape {
        &self.my_shape
    }

    /// `ChangeShape()` (private).
    fn change_shape(&mut self) -> &mut Shape {
        &mut self.my_shape
    }

    /// `GeneratedShapes(SpineShape, ProfShape)`: the shapes generated by a sub-shape of
    /// the spine and one of the profile; empty when none;
    /// `evo.generated_shapes(&spine_edge, &profile_edge)`.
    pub fn generated_shapes(&self, spine_shape: &Shape, prof_shape: &Shape) -> &List<Shape> {
        self.my_map
            .seek(spine_shape)
            .and_then(|m| m.seek(prof_shape))
            .unwrap_or(&self.my_empty)
    }

    /// `Generated()` (private): the map of the generated shapes.
    fn generated(&mut self) -> &mut EvolvedMap {
        &mut self.my_map
    }

    /// `JoinType()`; `evo.join_type()`.
    pub fn join_type(&self) -> JoinType {
        self.my_join_type
    }

    /// `Top()`: the top face of a solid result; `evo.top()`.
    pub fn top(&self) -> &Shape {
        &self.my_top
    }

    /// `Bottom()`: the bottom face of a solid result; `evo.bottom()`.
    pub fn bottom(&self) -> &Shape {
        &self.my_bottom
    }
}
