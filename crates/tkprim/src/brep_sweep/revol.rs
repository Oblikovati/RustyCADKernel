/// `BRepSweep_Revol`: the revolution of a shape (taken FORWARD) around an axis by an
/// angle, reduced into (0, 2PI] (a negative angle turns around the reversed axis).
///
/// ```
/// use rustycad_tkbrep::brep::BRepBuilder;
/// use rustycad_tkbrep::topods::Vertex;
/// use rustycad_tkg3d::top_abs::ShapeEnum;
/// use rustycad_tkmath::gp::{Axis1, Direction3, Point3};
/// use rustycad_tkprim::brep_sweep::BRepSweepRevol;
/// let mut vertex = Vertex::default();
/// BRepBuilder::default().make_vertex_at(&mut vertex, Point3::new(1.0, 0.0, 0.0), 1e-7)?;
/// let axis = Axis1::new(Point3::new(0.0, 0.0, 0.0), Direction3::new(0.0, 0.0, 1.0)?);
/// let mut revol = BRepSweepRevol::full(&vertex, axis, false)?;
/// assert_eq!(revol.shape()?.shape_type()?, ShapeEnum::Edge);
/// # Ok::<(), rustycad_tkernel::standard::Failure>(())
/// ```
pub struct BRepSweepRevol {
    my_rotation: BRepSweepRotation,
}

impl BRepSweepRevol {
    /// `BRepSweep_Revol(S, A, D, C)`: the revolution of `shape` around `axis` by `angle`
    /// (the sub-shapes copied when `copy`); Standard_ConstructionError for an angle that
    /// reduces to Precision::Angular() or less. The reduction subtracts 2PI until the
    /// angle is within 2PI + Precision::Angular(), so a huge angle never returns, as
    /// natively; `BRepSweepRevol::new(&shape, axis, 1.0, false)?`.
    pub fn new(shape: &Shape, axis: Axis1, angle: f64, copy: bool) -> Result<Self, Failure> {
        let my_rotation = Self::rotation(shape, axis, angle, copy)?;
        if Self::reduced_angle(angle) <= precision::angular() {
            return Err(Failure::with_message(
                "Standard_ConstructionError",
                &format!(
                    "BRepSweep_Revol::Constructor: angle {angle} reduces to {}; expected more than Precision::Angular()",
                    Self::reduced_angle(angle)
                ),
            ));
        }
        Ok(Self { my_rotation })
    }

    /// `BRepSweep_Revol(S, A, C)`: the complete revolution (2PI);
    /// `BRepSweepRevol::full(&shape, axis, false)?`.
    pub fn full(shape: &Shape, axis: Axis1, copy: bool) -> Result<Self, Failure> {
        Ok(Self {
            my_rotation: Self::rotation(shape, axis, 2.0 * PI, copy)?,
        })
    }

    /// The rotation of the constructors.
    fn rotation(
        shape: &Shape,
        axis: Axis1,
        angle: f64,
        copy: bool,
    ) -> Result<BRepSweepRotation, Failure> {
        let forward = shape.oriented(Orientation::Forward);
        let location = Self::location(axis, angle)?;
        BRepSweepRotation::new(
            &forward,
            Self::num_shape(angle),
            location,
            Self::axe_of(axis, angle),
            Self::reduced_angle(angle),
            copy,
        )
    }

    /// `Shape()`: the revolution; `revol.shape()?`.
    pub fn shape(&mut self) -> Result<Shape, Failure> {
        self.my_rotation.shape()
    }

    /// `Shape(aGenS)`: the shape generated by a sub-shape of the base;
    /// `revol.shape_of(&edge)?`.
    pub fn shape_of(&mut self, gen_s: &Shape) -> Result<Shape, Failure> {
        self.my_rotation.shape_of(gen_s)
    }

    /// `FirstShape()`: the first shape (the base); `revol.first_shape()?`.
    pub fn first_shape(&mut self) -> Result<Shape, Failure> {
        self.my_rotation.first_shape()
    }

    /// `FirstShape(aGenS)`: the first shape of a sub-shape of the base;
    /// `revol.first_shape_of(&edge)?`.
    pub fn first_shape_of(&mut self, gen_s: &Shape) -> Result<Shape, Failure> {
        self.my_rotation.first_shape_of(gen_s)
    }

    /// `LastShape()`: the last shape (the base rotated by the angle); `revol.last_shape()?`.
    pub fn last_shape(&mut self) -> Result<Shape, Failure> {
        self.my_rotation.last_shape()
    }

    /// `LastShape(aGenS)`: the last shape of a sub-shape of the base;
    /// `revol.last_shape_of(&edge)?`.
    pub fn last_shape_of(&mut self, gen_s: &Shape) -> Result<Shape, Failure> {
        self.my_rotation.last_shape_of(gen_s)
    }

    /// `Axe()`: the axis of the rotation; `revol.axe()`.
    pub fn axe(&self) -> Axis1 {
        self.my_rotation.axe()
    }

    /// `Angle()`: the reduced angle of the rotation; `revol.angle()`.
    pub fn angle(&self) -> f64 {
        self.my_rotation.angle()
    }

    /// `IsUsed(aGenS)`: whether a shape generated by `gen_s` is in the revolution;
    /// `revol.is_used(&edge)?`.
    pub fn is_used(&self, gen_s: &Shape) -> Result<bool, Failure> {
        self.my_rotation.is_used(gen_s)
    }

    /// The rotation sweep of the revolution.
    pub fn rotation_sweep(&self) -> &BRepSweepRotation {
        &self.my_rotation
    }

    /// `NumShape(D)`: the directing edge, closed (one vertex) for a complete revolution.
    fn num_shape(angle: f64) -> SweepNumShape {
        let mut n = SweepNumShape::default();
        if (Self::reduced_angle(angle) - 2.0 * PI).abs() <= precision::angular() {
            n.init(2, ShapeEnum::Edge, true, false, false);
        } else {
            n.init(2, ShapeEnum::Edge, false, false, false);
        }
        n
    }

    /// `Location(Ax, D)`: the rotation by the reduced angle around the oriented axis.
    fn location(axis: Axis1, angle: f64) -> Result<Location, Failure> {
        let mut transform = Transform3::default();
        transform.set_rotation(Self::axe_of(axis, angle), Self::reduced_angle(angle))?;
        Ok(Location::new(transform))
    }

    /// `Axe(Ax, D)`: the axis, reversed for a negative angle.
    fn axe_of(axis: Axis1, angle: f64) -> Axis1 {
        if angle < 0.0 {
            return axis.reversed();
        }
        axis
    }

    /// `Angle(D)`: |D| reduced by 2PI until it is at most 2PI + Precision::Angular().
    fn reduced_angle(angle: f64) -> f64 {
        let mut d = angle.abs();
        while d > 2.0 * PI + precision::angular() {
            d -= 2.0 * PI;
        }
        d
    }
}
