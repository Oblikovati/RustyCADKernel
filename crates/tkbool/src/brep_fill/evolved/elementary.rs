//! The elementary volevo of a profile part on one side of Oz: the tubes along the
//! spine edges and the revolutions at the spine vertices, trimmed by the edges of the
//! bisectors of the spine, then their parallel edges cut and their faces bounded.
use super::statics::edge_vertices;
use super::trim::{trim_edge, trim_face};
use super::{BRepFillEvolved, find2, find2_mut, first_of};
use rustycad_tkbrep::brep::BRepBuilder;
use rustycad_tkbrep::brep_tools::{self, WireExplorer};
use rustycad_tkbrep::topexp::Explorer;
use rustycad_tkbrep::topods::{self, Face, Shape, Wire};
use rustycad_tkbrep::toptools::{MapOfShape, ShapeMapHasher};
use rustycad_tkernel::ncollection::DataMap;
use rustycad_tkernel::standard::Failure;
use rustycad_tkg3d::top_abs::ShapeEnum;
use rustycad_tkmath::geom_abs::JoinType;
use rustycad_tkmath::gp::{self, Axis3, Point3};
use rustycad_tktopalgo::brep_mat2d::{BRepMAT2dBisectingLocus, BRepMAT2dLinkTopoBilo};

/// The edges and vertices generated by the bisectors on each face or parallel edge
/// (`MapBis`).
pub(super) type BisectorShapes = DataMap<Shape, Vec<Shape>, ShapeMapHasher>;
/// The parameters of the vertices of MapBis on each parallel edge (`MapVerPar`).
pub(super) type VertexParameters = DataMap<Shape, Vec<f64>, ShapeMapHasher>;

/// The frame of the profile: origin, Z and X.
pub(super) fn profile_frame() -> Result<Axis3, Failure> {
    Axis3::new(Point3::new(0., 0., 0.), gp::dz(), gp::dx())
}

impl BRepFillEvolved {
    /// The revolution at the last vertex of each spine edge with bisectors starting
    /// there, then the tube of each spine edge with bisectors.
    fn tubes_and_revolutions(
        &mut self,
        link: &mut BRepMAT2dLinkTopoBilo,
        axe_ref: &Axis3,
    ) -> Result<(), Failure> {
        for w in Explorer::new(self.my_spine.as_ref(), ShapeEnum::Wire, ShapeEnum::Shape)? {
            let mut wire_exp = WireExplorer::with_wire(&topods::wire(&w)?)?;
            while wire_exp.more() {
                let current_edge = wire_exp.current().clone();
                let (_, v_last) = edge_vertices(&current_edge);
                link.init(v_last.as_ref());
                while link.more()? {
                    self.make_revol(&current_edge, &v_last, axe_ref)?;
                    link.next();
                }
                link.init(current_edge.as_ref());
                while link.more()? {
                    self.make_pipe(&current_edge, axe_ref)?;
                    link.next();
                }
                wire_exp.next()?;
            }
        }
        Ok(())
    }

    /// The face controlling the parallel edge of `current_prof` at its first vertex:
    /// the face of the profile edge, else of the previous one, when it has bisectors.
    fn controle_face(
        &self,
        current_spine: &Shape,
        current_prof: &Shape,
        prec_prof: &Shape,
        map_bis: &BisectorShapes,
    ) -> Result<Option<Shape>, Failure> {
        let face_controle = first_of(find2(&self.my_map, current_spine, current_prof)?)?;
        if map_bis.is_bound(&face_controle) {
            return Ok(Some(face_controle));
        }
        if prec_prof.is_null() {
            return Ok(None);
        }
        let face_controle = first_of(find2(&self.my_map, current_spine, prec_prof)?)?;
        Ok(map_bis.is_bound(&face_controle).then_some(face_controle))
    }

    /// The parallel edge `current_edge` trimmed between its bisector vertices against
    /// the control face, the pieces appended to the shapes of (`spine`, `v`).
    fn trim_parallel(
        &mut self,
        spine: &Shape,
        v: &Shape,
        current_edge: &Shape,
        face_controle: &Shape,
        map_bis: &mut BisectorShapes,
        map_ver_par: &mut VertexParameters,
    ) -> Result<(), Failure> {
        let control = map_bis.seek(face_controle).cloned().unwrap_or_default();
        let mut ver = map_bis.seek(current_edge).cloned().unwrap_or_default();
        let mut par = map_ver_par.seek(current_edge).cloned().unwrap_or_default();
        let pieces = trim_edge(&topods::edge(current_edge)?, &control, &mut ver, &mut par)?;
        map_bis.bind(current_edge.clone(), ver);
        map_ver_par.bind(current_edge.clone(), par);
        let list = find2_mut(&mut self.my_map, spine, v)?;
        for p in pieces {
            list.append(p);
        }
        Ok(())
    }

    /// The parallel edges of one spine shape cut by the vertices of the bisectors;
    /// `prec_prof` is the previous profile edge, kept from one spine shape to the next
    /// as natively.
    fn parallel_edges_of(
        &mut self,
        current_spine: &Shape,
        prec_prof: &mut Shape,
        map_bis: &mut BisectorShapes,
        map_ver_par: &mut VertexParameters,
    ) -> Result<(), Failure> {
        let mut prof_exp = WireExplorer::with_wire(&self.my_profile)?;
        let (mut current_prof, mut vcl) = (Shape::default(), Shape::default());
        while prof_exp.more() {
            current_prof = prof_exp.current().as_ref().clone();
            let (vcf, vl) = edge_vertices(prof_exp.current());
            vcl = vl.as_ref().clone();
            let current_edge = first_of(find2(&self.my_map, current_spine, vcf.as_ref())?)?;
            if map_bis.is_bound(&current_edge)
                && let Some(face_controle) =
                    self.controle_face(current_spine, &current_prof, prec_prof, map_bis)?
            {
                self.trim_parallel(
                    current_spine,
                    vcf.as_ref(),
                    &current_edge,
                    &face_controle,
                    map_bis,
                    map_ver_par,
                )?;
            }
            *prec_prof = current_prof.clone();
            prof_exp.next()?;
        }
        // The parallel edge of the last vertex of the profile.
        let current_edge = first_of(find2(&self.my_map, current_spine, &vcl)?)?;
        if !map_bis.is_bound(&current_edge) {
            return Ok(());
        }
        let face_controle = first_of(find2(&self.my_map, current_spine, &current_prof)?)?;
        // The count of shapes tells whether the edges are done (closed profile).
        if map_bis.is_bound(&face_controle) && find2(&self.my_map, current_spine, &vcl)?.len() <= 1
        {
            self.trim_parallel(
                current_spine,
                &vcl,
                &current_edge,
                &face_controle,
                map_bis,
                map_ver_par,
            )?;
        }
        Ok(())
    }

    /// The trimming edges of a face completed with the parallel pieces at both ends of
    /// its profile edge, oriented as their first parallel edge in the face.
    fn complete_face_edges(
        &self,
        current_spine: &Shape,
        current_prof: &Shape,
        current_face: &Face,
        map_bis: &mut BisectorShapes,
    ) -> Result<(), Failure> {
        let (vcf, vcl) = edge_vertices(&topods::edge(current_prof)?);
        for v in [vcf, vcl] {
            let l: Vec<Shape> = find2(&self.my_map, current_spine, v.as_ref())?
                .iter()
                .cloned()
                .collect();
            let first = l
                .first()
                .ok_or_else(|| super::no_such("no parallel edge at a profile vertex"))?;
            let ori = brep_tools::ori_edge_in_face(&topods::edge(first)?, current_face)?;
            let edges = map_bis.try_emplaced(current_face.as_ref().clone(), Vec::new);
            for re in &l[1..] {
                edges.push(re.oriented(ori));
            }
        }
        Ok(())
    }

    /// The faces of one spine shape cut by their trimming edges (a face without
    /// bisector edges is dropped), then the edges of origin removed from the vertex
    /// lists.
    fn cut_faces_of(
        &mut self,
        current_spine: &Shape,
        map_bis: &mut BisectorShapes,
    ) -> Result<(), Failure> {
        let mut prof_exp = WireExplorer::with_wire(&self.my_profile)?;
        while prof_exp.more() {
            let current_prof = prof_exp.current().as_ref().clone();
            let current_face = topods::face(&first_of(find2(
                &self.my_map,
                current_spine,
                &current_prof,
            )?)?)?;
            find2_mut(&mut self.my_map, current_spine, &current_prof)?.clear();
            if map_bis.is_bound(current_face.as_ref()) {
                self.complete_face_edges(current_spine, &current_prof, &current_face, map_bis)?;
                let mut edges = map_bis
                    .change_seek(current_face.as_ref())
                    .map(std::mem::take)
                    .unwrap_or_default();
                let faces = trim_face(&current_face, &mut edges)?;
                map_bis.bind(current_face.as_ref().clone(), edges);
                for f in faces {
                    BRepBuilder::default().add(&mut self.my_shape, &f)?;
                    find2_mut(&mut self.my_map, current_spine, &current_prof)?.append(f);
                }
            }
            prof_exp.next()?;
        }
        let mut vmap = MapOfShape::default();
        for v in Explorer::new(
            self.my_profile.as_ref(),
            ShapeEnum::Vertex,
            ShapeEnum::Shape,
        )? {
            if vmap.add(v.clone()) {
                find2_mut(&mut self.my_map, current_spine, &v)?.remove_first()?;
            }
        }
        Ok(())
    }

    /// `ElementaryPerform(Spine, Profile, Locus, Link, Join)` (private): the tubes and
    /// revolutions, the edges of the bisectors on them, the parallel edges cut and the
    /// faces bounded.
    pub(super) fn elementary_perform(
        &mut self,
        sp: &Face,
        pr: &Wire,
        locus: &BRepMAT2dBisectingLocus,
        link: &mut BRepMAT2dLinkTopoBilo,
        _join: JoinType,
    ) -> Result<(), Failure> {
        self.start_volevo(sp, pr)?;
        let axe_ref = profile_frame()?;
        self.tubes_and_revolutions(link, &axe_ref)?;
        let (mut map_bis, mut map_ver_par) =
            (BisectorShapes::default(), VertexParameters::default());
        self.bisector_edges(locus, link, &mut map_bis, &mut map_ver_par)?;
        let spines: Vec<Shape> = self.my_map.items().map(|(k, _)| k.clone()).collect();
        let mut prec_prof = Shape::default();
        for current_spine in &spines {
            self.parallel_edges_of(
                current_spine,
                &mut prec_prof,
                &mut map_bis,
                &mut map_ver_par,
            )?;
        }
        for current_spine in &spines {
            self.cut_faces_of(current_spine, &mut map_bis)?;
        }
        self.my_is_done = true;
        Ok(())
    }
}
