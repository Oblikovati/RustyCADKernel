/// `BRepPrimAPI_MakeRevol`: the revolution of a shape around an axis by an angle (the
/// whole turn by default). A shape with an edge crossing the axis gives a null shape and
/// a maker that is not done; the degenerated edges shared by several faces are copied
/// per face, with their history (docs/prim-design.md section 4).
///
/// ```
/// use rustycad_tkbrep::topods::Shape;
/// use rustycad_tkmath::gp::{Axis1, Direction3, Point3};
/// use rustycad_tkprim::brep_prim_api::BRepPrimAPIMakeRevol;
/// use rustycad_tktopalgo::brep_builder_api::{BRepBuilderAPIMakeShape, BRepBuilderAPIMakeVertex};
/// let vertex: Shape = BRepBuilderAPIMakeVertex::new(Point3::new(1.0, 0.0, 0.0))?.vertex()?.into();
/// let axis = Axis1::new(Point3::new(0.0, 0.0, 0.0), Direction3::new(0.0, 0.0, 1.0)?);
/// let mut maker = BRepPrimAPIMakeRevol::full(&vertex, axis, false)?;
/// assert!(maker.is_done());
/// assert!(!maker.shape()?.is_null());
/// # Ok::<(), rustycad_tkernel::standard::Failure>(())
/// ```
pub struct BRepPrimAPIMakeRevol {
    pub(super) base: BRepBuilderAPIMakeShapeBase,
    pub(super) my_revol: BRepSweepRevol,
    pub(super) my_degenerated: List<Shape>,
    pub(super) my_hist: Handle<History>,
    pub(super) my_is_build: bool,
}

impl BRepPrimAPIMakeRevol {
    /// The constructor body: a null shape when the shape crosses the axis, else the
    /// built revolution.
    fn validated(shape: &Shape, axis: Axis1, my_revol: BRepSweepRevol) -> Result<Self, Failure> {
        let mut maker = Self {
            base: BRepBuilderAPIMakeShapeBase::new(),
            my_revol,
            my_degenerated: List::default(),
            my_hist: Handle::default(),
            my_is_build: false,
        };
        if !maker.check_validity(check(shape)?, axis)? {
            maker.base.my_shape.nullify();
            maker.my_is_build = true;
            return Ok(maker);
        }
        maker.build(&ProgressRange::default())?;
        Ok(maker)
    }

    /// `BRepPrimAPI_MakeRevol(S, A, D, Copy = false)`: the revolution of `shape` around
    /// `axis` by the angle `d`; `BRepPrimAPIMakeRevol::new(&shape, axis, 1.0, false)?`.
    pub fn new(shape: &Shape, axis: Axis1, d: f64, copy: bool) -> Result<Self, Failure> {
        let my_revol = BRepSweepRevol::new(check(shape)?, axis, d, copy)?;
        Self::validated(shape, axis, my_revol)
    }

    /// `BRepPrimAPI_MakeRevol(S, A, Copy = false)`: the whole turn (the angle 2*PI, not
    /// the closed sweep of `BRepSweep_Revol(S, A, Copy)`);
    /// `BRepPrimAPIMakeRevol::full(&shape, axis, false)?`.
    pub fn full(shape: &Shape, axis: Axis1, copy: bool) -> Result<Self, Failure> {
        let my_revol = BRepSweepRevol::new(check(shape)?, axis, 2. * PI, copy)?;
        Self::validated(shape, axis, my_revol)
    }

    /// `Revol()`: the sweep algorithm; `maker.revol()`.
    pub fn revol(&self) -> &BRepSweepRevol {
        &self.my_revol
    }

    /// `FirstShape(theShape)`: the first shape generated by a sub-shape of the base;
    /// `maker.first_shape_of(&edge)?`.
    pub fn first_shape_of(&mut self, shape: &Shape) -> Result<Shape, Failure> {
        self.my_revol.first_shape_of(shape)
    }

    /// `LastShape(theShape)`: the last shape generated by a sub-shape of the base;
    /// `maker.last_shape_of(&edge)?`.
    pub fn last_shape_of(&mut self, shape: &Shape) -> Result<Shape, Failure> {
        self.my_revol.last_shape_of(shape)
    }

    /// `HasDegenerated()`: the revolution has degenerated edges;
    /// `maker.has_degenerated()`.
    pub fn has_degenerated(&self) -> bool {
        !self.my_degenerated.is_empty()
    }

    /// `Degenerated()`: the degenerated edges of the revolution and their per-face
    /// copies; `maker.degenerated()`.
    pub fn degenerated(&self) -> &List<Shape> {
        &self.my_degenerated
    }

    /// The degenerated-edge part of `Generated`: `generated` (a degenerated edge) and its
    /// copies when it is a recorded degenerated edge, else nothing.
    fn generated_degenerated(&mut self, generated: &Shape) -> Result<(), Failure> {
        let same_count = self.my_degenerated.iter().filter(|edge| generated.is_same(edge)).count();
        for _ in 0..same_count {
            self.base.my_generated.append(generated.clone());
            let Some(history) = self.my_hist.get() else {
                continue;
            };
            for modified in history.modified(generated)? {
                self.base.my_generated.append(modified);
            }
            return Ok(());
        }
        Ok(())
    }

    /// The general part of `Generated`: `generated`, or its modifications when the
    /// history has some.
    fn generated_modified(&mut self, generated: &Shape) -> Result<(), Failure> {
        let modified = match self.my_hist.get() {
            Some(history) => history.modified(generated)?,
            None => Vec::new(),
        };
        if modified.is_empty() {
            self.base.my_generated.append(generated.clone());
            return Ok(());
        }
        for shape in modified {
            self.base.my_generated.append(shape);
        }
        Ok(())
    }

    /// Whether `generated` is a degenerated edge.
    fn is_degenerated_edge(generated: &Shape) -> Result<bool, Failure> {
        if generated.shape_type()? != rustycad_tkg3d::top_abs::ShapeEnum::Edge {
            return Ok(false);
        }
        BRepTool::degenerated(&Edge::unchecked(generated.clone()))
    }
}

impl BRepBuilderAPIMakeShape for BRepPrimAPIMakeRevol {
    fn make_shape_base(&self) -> &BRepBuilderAPIMakeShapeBase {
        &self.base
    }

    fn make_shape_base_mut(&mut self) -> &mut BRepBuilderAPIMakeShapeBase {
        &mut self.base
    }

    /// `Build()`: once, the revolution becomes the shape, the inner tolerances are
    /// updated and each face gets its own copy of a shared degenerated edge.
    fn build(&mut self, _range: &ProgressRange<'_>) -> Result<(), Failure> {
        if self.my_is_build {
            return Ok(());
        }
        self.build_revolution()
    }

    /// `Generated(S)`: the shape generated by `S` (with its copies for a degenerated
    /// edge, or its modifications by the copying of the degenerated edges).
    fn generated(&mut self, shape: &Shape) -> Result<&List<Shape>, Failure> {
        self.base.my_generated.clear();
        if !self.my_revol.is_used(shape)? {
            return Ok(&self.base.my_generated);
        }
        let generated = self.my_revol.shape_of(shape)?;
        if generated.is_null() || !History::is_supported_type(&generated)? {
            return Ok(&self.base.my_generated);
        }
        if Self::is_degenerated_edge(&generated)? {
            self.generated_degenerated(&generated)?;
        } else {
            self.generated_modified(&generated)?;
        }
        Ok(&self.base.my_generated)
    }

    /// `IsDeleted(S)`: no shape generated by `S` is in the revolution.
    fn is_deleted(&mut self, shape: &Shape) -> Result<bool, Failure> {
        Ok(!self.my_revol.is_used(shape)?)
    }
}

