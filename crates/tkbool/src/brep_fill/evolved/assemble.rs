    /// The edges generated by a common profile vertex in both volevos bound in the quilt
    /// (the volevo edge onto this one, oriented by their first points).
    fn bind_common_edges(&self, vevo: &Self, vv: &Shape, glue: &mut Quilt) -> Result<(), Failure> {
        for (sp, inner) in self.my_map.items() {
            let Some(my_list) = inner.seek(vv) else {
                continue;
            };
            if !vevo.my_map.seek(sp).is_some_and(|m| m.is_bound(vv)) {
                continue;
            }
            let mut vevo_it = vevo.generated_shapes(sp, vv).iter();
            for me in my_list.iter() {
                let ve = vevo_it.next().ok_or_else(|| {
                    super::no_such("fewer volevo edges than edges at a common vertex")
                })?;
                let (me, ve) = (topods::edge(me)?, topods::edge(ve)?);
                let og = compare(&me, &ve)?;
                glue.bind_edge(
                    &topods::edge(&ve.as_ref().oriented(Orientation::Forward))?,
                    &topods::edge(&me.as_ref().oriented(og))?,
                )?;
            }
        }
        Ok(())
    }

    /// `Add(Vevo, Prof, Glue)` (private): the volevo of the profile part `prof` glued:
    /// its edges at profile vertices common with this profile bound in the quilt, its
    /// shape added, and its map merged (with the quilt copies).
    pub(super) fn add(
        &mut self,
        vevo: &mut Self,
        prof: &topods::Wire,
        glue: &mut Quilt,
    ) -> Result<(), Failure> {
        if vevo.shape().is_null() {
            return Ok(());
        }
        for vv in Explorer::new(prof.as_ref(), ShapeEnum::Vertex, ShapeEnum::Shape)? {
            let (_, commun) = relative(&self.my_profile, prof, &topods::vertex(&vv)?)?;
            if commun {
                self.bind_common_edges(vevo, &vv, glue)?;
            }
        }
        glue.add(vevo.shape())?;
        for (current_spine, inner) in vevo.generated().items() {
            for (current_prof, gen_shapes) in inner.items() {
                let mine = self
                    .my_map
                    .try_emplaced(current_spine.clone(), ProfileGenerated::default);
                if mine.is_bound(current_prof) {
                    continue;
                }
                let mut l = List::default();
                for s in gen_shapes.iter() {
                    // during Glue.Add the shared shapes are recreated.
                    l.append(if glue.is_copied(s) {
                        glue.copy(s)?
                    } else {
                        s.clone()
                    });
                }
                mine.bind(current_prof.clone(), l);
            }
        }
        Ok(())
    }

    /// The edges of the shape with SameRange and SameParameter forced (expecting for
    /// better, as natively: the planar and tube parts disagree on SameParameter).
    fn force_same_parameter(&self) -> Result<(), Failure> {
        let b = BRepBuilder::default();
        for e in Explorer::new(&self.my_shape, ShapeEnum::Edge, ShapeEnum::Shape)? {
            let e = topods::edge(&e)?;
            b.same_range(&e, false)?;
            b.same_parameter(&e, false)?;
            brep_lib::same_parameter_edge(&e, 1.0e-5)?;
        }
        Ok(())
    }

    /// `Transfert(Vevo, MapProf, MapSpine, LS, InitLS, InitLP)` (private): the shape
    /// and the map of the volevo moved back by `ls` onto the initial spine and profile
    /// shapes (the lists of the volevo are emptied, NCollection_List::Append(List)),
    /// with its top and bottom.
    pub(super) fn transfert(
        &mut self,
        vevo: &mut Self,
        map_prof: &ShapeOrigins,
        map_spine: &ShapeOrigins,
        ls: &Location,
        init_ls: &Location,
        init_lp: &Location,
    ) -> Result<(), Failure> {
        self.my_shape = vevo.shape().clone();
        let mut spine = self.my_spine.as_ref().clone();
        spine.set_location(init_ls, true)?;
        self.my_spine = topods::face(&spine)?;
        let mut profile = self.my_profile.as_ref().clone();
        profile.set_location(init_lp, true)?;
        self.my_profile = topods::wire(&profile)?;
        self.my_shape.move_by(ls, true)?;
        self.force_same_parameter()?;
        let spines: Vec<Shape> = vevo.my_map.items().map(|(k, _)| k.clone()).collect();
        for key_s in &spines {
            let mut initial_spine = map_spine
                .seek(key_s)
                .cloned()
                .ok_or_else(|| super::no_such("a spine shape without origin"))?;
            initial_spine.move_by(ls, true)?;
            let inner = vevo
                .my_map
                .change_seek(key_s)
                .ok_or_else(|| super::no_such("a spine shape of the volevo"))?;
            let profs: Vec<Shape> = inner.items().map(|(k, _)| k.clone()).collect();
            for key_p in &profs {
                let mut initial_prof = map_prof
                    .seek(key_p)
                    .cloned()
                    .ok_or_else(|| super::no_such("a profile shape without origin"))?;
                initial_prof.set_location(init_lp, true)?;
                let gen_shapes = inner
                    .change_seek(key_p)
                    .map(std::mem::take)
                    .unwrap_or_default();
                let mut moved = Vec::with_capacity(gen_shapes.len());
                for mut s in gen_shapes.iter().cloned() {
                    s.move_by(ls, true)?;
                    moved.push(s);
                }
                self.append_generated(&initial_spine, &initial_prof, moved);
            }
        }
        self.my_top = vevo.top().clone();
        self.my_top.move_by(ls, true)?;
        self.my_bottom = vevo.bottom().clone();
        self.my_bottom.move_by(ls, true)?;
        Ok(())
    }

    /// The edges generated by the spine edges at the profile vertex `v` added to the
    /// loop, oriented as their spine edge (reversed when the tangents disagree; the
    /// decision of the first edge of each spine edge, kept in `to_reverse`).
    fn cap_edges_of_spine_edges(
        &self,
        v: &Shape,
        lp: &mut BRepAlgoLoop,
        to_reverse: &mut bool,
    ) -> Result<(), Failure> {
        for es in Explorer::new(self.my_spine.as_ref(), ShapeEnum::Edge, ShapeEnum::Shape)? {
            let es_edge = topods::edge(&es)?;
            let mut compute_orientation = false;
            for e in self.generated_shapes(&es, v).iter() {
                let e = topods::edge(e)?;
                if !compute_orientation {
                    let (c1, c2) = (
                        BRepAdaptorCurve::with_edge(&es_edge)?,
                        BRepAdaptorCurve::with_edge(&e)?,
                    );
                    let ((f, l), (fs, ls)) = (BRepTool::range(&e)?, BRepTool::range(&es_edge)?);
                    let v1 = c1.d1(0.3 * fs + 0.7 * ls)?.1;
                    let v2 = c2.d1(0.3 * f + 0.7 * l)?.1;
                    *to_reverse = v1.dot(v2) < 0.;
                    compute_orientation = true;
                }
                let or = if *to_reverse {
                    top_abs::reverse(es.orientation())
                } else {
                    es.orientation()
                };
                lp.add_const_edge(&topods::edge(&e.as_ref().oriented(or))?);
            }
        }
        Ok(())
    }

    /// The circles generated by the spine vertices at the profile vertex `v` added to
    /// the loop, turning so that their centre is in the cap for a profile vertex out
    /// (Y < 0) and out of it otherwise.
    fn cap_edges_of_spine_vertices(
        &self,
        v: &Vertex,
        lp: &mut BRepAlgoLoop,
        to_reverse: &mut bool,
    ) -> Result<(), Failure> {
        let is_out = BRepTool::pnt(v)?.y() < 0.;
        let mut view = MapOfShape::default();
        for es in Explorer::new(self.my_spine.as_ref(), ShapeEnum::Vertex, ShapeEnum::Shape)? {
            if !view.add(es.clone()) {
                continue;
            }
            let p = BRepTool::pnt(&topods::vertex(&es)?)?;
            for e in self.generated_shapes(&es, v.as_ref()).iter() {
                let e = topods::edge(e)?;
                if BRepTool::degenerated(&e)? {
                    continue;
                }
                let c = BRepAdaptorCurve::with_edge(&e)?;
                let (f, l) = BRepTool::range(&e)?;
                let (pc, vc) = c.d1(0.3 * f + 0.7 * l)?;
                let prod = Vector3::between(p, pc).crossed(vc);
                *to_reverse = if is_out { prod.z() < 0. } else { prod.z() > 0. };
                let or = if *to_reverse {
                    Orientation::Reversed
                } else {
                    Orientation::Forward
                };
                lp.add_const_edge(&topods::edge(&e.as_ref().oriented(or))?);
            }
        }
        Ok(())
    }

    /// The faces of a cap, glued, kept as top (`i` 0) or bottom (a compound for several).
    fn keep_cap(&mut self, i: usize, faces: &List<Shape>, glue: &mut Quilt) -> Result<(), Failure> {
        let b = BRepBuilder::default();
        let mut bouchon = Compound::default();
        b.make_compound(&mut bouchon);
        let mut bouchon = bouchon.into_shape();
        for (j, f) in faces.iter().enumerate() {
            glue.add(f)?;
            if j == 0 {
                *(if i == 0 {
                    &mut self.my_top
                } else {
                    &mut self.my_bottom
                }) = f.clone();
            }
            b.add(&mut bouchon, f)?;
        }
        if faces.len() > 1 {
            *(if i == 0 {
                &mut self.my_top
            } else {
                &mut self.my_bottom
            }) = bouchon;
        }
        Ok(())
    }

    /// `AddTopAndBottom(Glue)` (private): for an open profile, the caps at its end
    /// vertices: the faces of the loops of the edges generated there on the horizontal
    /// planes, glued and kept as top and bottom.
    pub(super) fn add_top_and_bottom(&mut self, glue: &mut Quilt) -> Result<(), Failure> {
        let (v0, v1) = topexp::wire_vertices(&self.my_profile);
        if v0.as_ref().is_same(v1.as_ref()) {
            return Ok(());
        }
        let mut to_reverse = false;
        for (i, v) in [v0, v1].iter().enumerate() {
            let mut lp = BRepAlgoLoop::new();
            let f = BRepLibMakeFace::from_plane(Plane3::from_equation(0., 0., 1., -altitud(v)?)?)?
                .face()?;
            lp.init(&f);
            self.cap_edges_of_spine_edges(v.as_ref(), &mut lp, &mut to_reverse)?;
            self.cap_edges_of_spine_vertices(v, &mut lp, &mut to_reverse)?;
            lp.perform()?;
            lp.wires_to_faces()?;
            let faces = lp.new_faces().clone();
            self.keep_cap(i, &faces, glue)?;
        }
        Ok(())
    }

    /// `MakeSolid()` (private): a solid per shell, reversed when the infinite point is
    /// IN; the solid alone, else a compound of them.
    pub(super) fn make_solid(&mut self) -> Result<(), Failure> {
        let b = BRepBuilder::default();
        let mut res = Compound::default();
        b.make_compound(&mut res);
        let mut res = res.into_shape();
        let (mut ish, mut sol) = (0, Shape::default());
        for sh in Explorer::new(&self.my_shape, ShapeEnum::Shell, ShapeEnum::Shape)? {
            sol = Self::solid_of(&b, &sh)?;
            let mut sc = BRepClass3dSolidClassifier::with_shape(&sol)?;
            sc.perform_infinite_point(confusion())?;
            if sc.state() == State::In {
                sol = Self::solid_of(&b, &sh.reversed())?;
            }
            b.add(&mut res, &sol)?;
            ish += 1;
        }
        self.my_shape = if ish == 1 { sol } else { res };
        Ok(())
    }

    /// A new solid of one shell.
    fn solid_of(b: &BRepBuilder, sh: &Shape) -> Result<Shape, Failure> {
        let mut sol = Solid::default();
        b.make_solid(&mut sol);
        let mut sol = sol.into_shape();
        b.add(&mut sol, sh)?;
        Ok(sol)
    }

    /// The regularity of two profile edges at `v` (G1 or more) coded on the edges
    /// generated by `v` between the faces generated by the edges, for every spine
    /// shape.
    fn code_continuity(&self, v: &Vertex, cur_e: &Edge, other_e: &Edge) -> Result<(), Failure> {
        let u1 = BRepTool::parameter(v, cur_e)?;
        let u2 = BRepTool::parameter(v, other_e)?;
        let (curve1, curve2) = (
            BRepAdaptorCurve::with_edge(cur_e)?,
            BRepAdaptorCurve::with_edge(other_e)?,
        );
        let continuity = brep_lprop::continuity(&curve1, &curve2, u1, u2)?;
        if (continuity as i32) < (Continuity::G1 as i32) {
            return Ok(());
        }
        let b = BRepBuilder::default();
        for (_, m) in self.my_map.items() {
            let (Some(lv), Some(lc), Some(lo)) = (
                m.seek(v.as_ref()),
                m.seek(cur_e.as_ref()),
                m.seek(other_e.as_ref()),
            ) else {
                continue;
            };
            if lv.is_empty() || lc.is_empty() || lo.is_empty() {
                continue;
            }
            let (e, f1, f2) = (
                topods::edge(&first_of(lv)?)?,
                topods::face(&first_of(lc)?)?,
                topods::face(&first_of(lo)?)?,
            );
            b.continuity_on_faces(&e, &f1, &f2, continuity)?;
        }
        Ok(())
    }

    /// `ContinuityOnOffsetEdge(WorkProf)` (private): the regularities between the
    /// faces generated by consecutive profile edges at their vertices on Oz (and at
    /// the closing vertex of a closed profile).
    pub(super) fn continuity_on_offset_edge(
        &self,
        _work_prof: &List<Shape>,
    ) -> Result<(), Failure> {
        let mut wexp = WireExplorer::with_wire(&self.my_profile)?;
        let first_e = wexp.current().clone();
        let mut prec_e = first_e.clone();
        let (vf, _) = edge_vertices(&first_e);
        if wexp.more() {
            wexp.next()?;
        }
        let mut cur_e = Edge::default();
        while wexp.more() {
            cur_e = wexp.current().clone();
            let v = wexp.current_vertex().clone();
            if distance_to_oz(&v)? <= confusion() {
                // the regularities are already coded on the edges of elementary volevos
                self.code_continuity(&v, &cur_e, &prec_e)?;
            }
            prec_e = cur_e.clone();
            wexp.next()?;
        }
        let (_, vl) = edge_vertices(&prec_e);
        if vf.as_ref().is_same(vl.as_ref()) {
            // Closed profile.
            self.code_continuity(&vf, &cur_e, &first_e)?;
        }
        Ok(())
    }
