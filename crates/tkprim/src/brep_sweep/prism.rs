//! `BRepSweep_Prism`: the natural constructors of the translation sweeps.
use super::{BRepSweepNumLinearRegularSweep, BRepSweepTranslation};
use crate::sweep::SweepNumShape;
use rustycad_tkbrep::topods::Shape;
use rustycad_tkernel::precision;
use rustycad_tkernel::standard::Failure;
use rustycad_tkg3d::top_abs::ShapeEnum;
use rustycad_tkmath::gp::{Direction3, Transform3, Vector3};
use rustycad_tkmath::toploc::Location;

/// `BRepSweep_Prism`: the prism of a shape along a vector, or the semi-infinite or
/// infinite prism along a direction.
///
/// ```
/// use rustycad_tkbrep::brep::BRepBuilder;
/// use rustycad_tkbrep::topods::Vertex;
/// use rustycad_tkg3d::top_abs::ShapeEnum;
/// use rustycad_tkmath::gp::{Point3, Vector3};
/// use rustycad_tkprim::brep_sweep::BRepSweepPrism;
/// let mut vertex = Vertex::default();
/// BRepBuilder::default().make_vertex_at(&mut vertex, Point3::new(0.0, 0.0, 0.0), 1e-7)?;
/// let mut prism = BRepSweepPrism::new(&vertex, Vector3::new(0.0, 0.0, 2.0), false, true)?;
/// assert_eq!(prism.shape()?.shape_type()?, ShapeEnum::Edge);
/// assert!(!prism.last_shape()?.is_null());
/// # Ok::<(), rustycad_tkernel::standard::Failure>(())
/// ```
pub struct BRepSweepPrism {
    my_translation: BRepSweepTranslation,
}

impl BRepSweepPrism {
    /// `BRepSweep_Prism(S, V, Copy, Canonize)`: the prism of `shape` along `vector` (the
    /// sub-shapes copied when `copy`, the side surfaces canonized when `canonize`);
    /// Standard_ConstructionError for a vector not longer than Precision::Confusion();
    /// `BRepSweepPrism::new(&shape, v, false, true)?`.
    pub fn new(
        shape: &Shape,
        vector: Vector3,
        copy: bool,
        canonize: bool,
    ) -> Result<Self, Failure> {
        let my_translation = BRepSweepTranslation::new(
            shape,
            Self::num_shape(),
            Self::location(vector),
            vector,
            copy,
            canonize,
        )?;
        if vector.magnitude() <= precision::confusion() {
            return Err(Failure::with_message(
                "Standard_ConstructionError",
                &format!(
                    "BRepSweep_Prism::Constructor: vector of magnitude {}; expected more than Precision::Confusion()",
                    vector.magnitude()
                ),
            ));
        }
        Ok(Self { my_translation })
    }

    /// `BRepSweep_Prism(S, D, Inf, Copy, Canonize)`: the infinite prism of `shape` along
    /// `direction` (semi-infinite toward `direction` unless `inf`);
    /// `BRepSweepPrism::infinite(&shape, d, true, false, true)?`.
    pub fn infinite(
        shape: &Shape,
        direction: Direction3,
        inf: bool,
        copy: bool,
        canonize: bool,
    ) -> Result<Self, Failure> {
        let vector = Vector3::from(direction);
        let my_translation = BRepSweepTranslation::new(
            shape,
            Self::num_shape_infinite(inf),
            Self::location(vector),
            vector,
            copy,
            canonize,
        )?;
        Ok(Self { my_translation })
    }

    /// `Shape()`: the prism; `prism.shape()?`.
    pub fn shape(&mut self) -> Result<Shape, Failure> {
        self.my_translation.shape()
    }

    /// `Shape(aGenS)`: the shape generated by a sub-shape of the base;
    /// `prism.shape_of(&edge)?`.
    pub fn shape_of(&mut self, gen_s: &Shape) -> Result<Shape, Failure> {
        self.my_translation.shape_of(gen_s)
    }

    /// `FirstShape()`: the bottom of the prism; `prism.first_shape()?`.
    pub fn first_shape(&mut self) -> Result<Shape, Failure> {
        self.my_translation.first_shape()
    }

    /// `FirstShape(aGenS)`: the bottom shape of a sub-shape of the base;
    /// `prism.first_shape_of(&edge)?`.
    pub fn first_shape_of(&mut self, gen_s: &Shape) -> Result<Shape, Failure> {
        self.my_translation.first_shape_of(gen_s)
    }

    /// `LastShape()`: the top of the prism; `prism.last_shape()?`.
    pub fn last_shape(&mut self) -> Result<Shape, Failure> {
        self.my_translation.last_shape()
    }

    /// `LastShape(aGenS)`: the top shape of a sub-shape of the base;
    /// `prism.last_shape_of(&edge)?`.
    pub fn last_shape_of(&mut self, gen_s: &Shape) -> Result<Shape, Failure> {
        self.my_translation.last_shape_of(gen_s)
    }

    /// `Vec()`: the vector of the prism (unit for an infinite prism); `prism.vec()`.
    pub fn vec(&self) -> Vector3 {
        self.my_translation.vec()
    }

    /// `IsUsed(aGenS)`: whether a shape generated by `gen_s` is in the prism;
    /// `prism.is_used(&edge)?`.
    pub fn is_used(&self, gen_s: &Shape) -> Result<bool, Failure> {
        self.my_translation.is_used(gen_s)
    }

    /// `GenIsUsed(theS)`: whether the base shape of `gen_s` is in the prism;
    /// `prism.gen_is_used(&edge)?`.
    pub fn gen_is_used(&self, gen_s: &Shape) -> Result<bool, Failure> {
        self.my_translation.gen_is_used(gen_s)
    }

    /// The translation sweep of the prism.
    pub fn translation(&self) -> &BRepSweepTranslation {
        &self.my_translation
    }

    /// `NumShape()`: the directing edge of a finite prism (2 vertices).
    fn num_shape() -> SweepNumShape {
        SweepNumShape::new(2, ShapeEnum::Edge)
    }

    /// `NumShape(Inf)`: the directing edge of an infinite prism (no vertex) or of a
    /// semi-infinite one (one vertex, infinite at its end).
    fn num_shape_infinite(inf: bool) -> SweepNumShape {
        let mut n = SweepNumShape::default();
        if inf {
            n.init(0, ShapeEnum::Edge, false, true, true);
        } else {
            n.init(1, ShapeEnum::Edge, false, false, true);
        }
        n
    }

    /// `Location(V)`: the translation by `vector`.
    fn location(vector: Vector3) -> Location {
        let mut transform = Transform3::default();
        transform.set_translation(vector);
        Location::new(transform)
    }
}
