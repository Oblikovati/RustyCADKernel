#!/usr/bin/env python3
"""Carry the AdvApp2Var common-block tables over from the pinned OCCT sources verbatim.

Usage: python3 tools/generate_advapp2var_tables.py --source ../OCCT [--check]

AdvApp2Var_Data_M*.pxx initialise each Fortran common block (MLGDRTL, MMJCOBI,
MMCMCNP, MMAPGSS, MMAPGS0, MMAPGS1, MMAPGS2) from one flat `double` array that the
f2c code reinterprets as the block's struct. Every literal is copied as text, so the
Rust compiler rounds exactly the decimal strings the C++ compiler rounds; the only
rewrite is a `0` in front of a leading decimal point, which Rust requires and which
does not change the value. The output is fixed-size fragments that the hand-written
crates/tkgeombase/src/adv_app2var/data module flattens once.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT/'crates/tkgeombase/src/adv_app2var/data'
PACKAGE = 'src/ModelingData/TKGeomBase/AdvApp2Var'
CHUNK = 1920
PER_LINE = 4
LITERAL = re.compile(r'static double \w+\[(\d+)\]\s*=\s*\{(.*?)\};', re.S)
# Common block name -> pxx file stem, as AdvApp2Var_Data.pxx declares them.
BLOCKS = {'mlgdrtl': 'Mlgdrtl', 'mmjcobi': 'Mmjcobi', 'mmcmcnp': 'Mmcmcnp', 'mmapgss': 'Mmapgss',
          'mmapgs0': 'Mmapgs0', 'mmapgs1': 'Mmapgs1', 'mmapgs2': 'Mmapgs2'}


def rust_literal(token: str) -> str:
    """Spell a C double literal as a Rust one with the same decimal value; rust_literal('-.5')."""
    if token.startswith('.'): return '0'+token
    if token.startswith('-.'): return '-0'+token[1:]
    return token


def parse_block(text: str) -> list[str]:
    """Return the flat initialiser of one common block; parse_block(pxx_text)."""
    body = re.sub(r'//[^\n]*|/\*.*?\*/', ' ', text, flags=re.S)
    size, values = LITERAL.search(body).groups()
    tokens = [rust_literal(token.strip()) for token in values.split(',') if token.strip()]
    if len(tokens) != int(size): raise ValueError(f'{len(tokens)} literals; expected {size}')
    return tokens


def fragment(values: list[str]) -> str:
    """Render one include!-able array fragment; fragment(['1.0', '2.0'])."""
    rows = [', '.join(values[index:index+PER_LINE]) for index in range(0, len(values), PER_LINE)]
    return '&[\n'+''.join(f'    {row},\n' for row in rows)+']\n'


def index_module(blocks: dict[str, list[str]]) -> str:
    """Emit the fragment lists of every block; index_module(blocks)."""
    lines = [INDEX_PRELUDE]
    for name, values in blocks.items():
        includes = ''.join(f'    include!("tables/{name}_{index}.rs"),\n'
                           for index in range((len(values)+CHUNK-1)//CHUNK))
        lines.append(f'/// Verbatim `{name}_` initialiser ({len(values)} values).\n'
                     f'pub(super) const {name.upper()}: &[&[f64]] = &[\n{includes}];\n')
    return '\n'.join(lines)


INDEX_PRELUDE = '''//! Common-block tables generated by tools/generate_advapp2var_tables.py; do not edit.
//!
//! The literals come verbatim from AdvApp2Var_Data_M*.pxx at
//! 3d097a0328e71b826377d4814ab05ec3c3d23871, split into fragments of '''+str(CHUNK)+''' values.
// The literals are the native ones, even where one equals a std constant.
#![allow(clippy::excessive_precision, clippy::approx_constant)]
'''


def generate(source: Path) -> dict[Path, str]:
    """Render every generated file; generate(Path('../OCCT'))."""
    blocks, output = {}, {}
    for name, stem in BLOCKS.items():
        text = (source/PACKAGE/f'AdvApp2Var_Data_{stem}.pxx').read_text()
        values = blocks[name] = parse_block(text)
        for index in range(0, len(values), CHUNK):
            path = TARGET/'tables'/f'{name}_{index//CHUNK}.rs'
            output[path] = fragment(values[index:index+CHUNK])
    output[TARGET/'tables.rs'] = index_module(blocks)
    return output


def main() -> int:
    """Write or check the generated tables; exit 1 when --check finds drift."""
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, default=ROOT/'../OCCT')
    parser.add_argument('--check', action='store_true')
    arguments = parser.parse_args()
    output = generate(arguments.source.resolve())
    stale = [path for path, text in output.items() if not path.exists() or path.read_text() != text]
    if arguments.check:
        for path in stale: print(f'stale generated table: {path.relative_to(ROOT)}')
        return 1 if stale else 0
    (TARGET/'tables').mkdir(parents=True, exist_ok=True)
    for path in stale: path.write_text(output[path])
    print(f'{len(output)} files, {len(stale)} written')
    return 0


if __name__ == '__main__':
    sys.exit(main())
