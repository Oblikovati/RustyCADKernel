//! The blended shape: the untouched faces, the tubes and the faces of the shape
//! rebuilt on their unwound offsets, sewn together.
use super::BiTgteBlend;
use super::statics::live;
use rustycad_tkbrep::brep::{BRepBuilder, BRepTool};
use rustycad_tkbrep::brep_tools;
use rustycad_tkbrep::topexp::{self, Explorer};
use rustycad_tkbrep::topods::{self, Edge, Face, Shape, Vertex, Wire};
use rustycad_tkbrep::toptools::ShapeMapHasher;
use rustycad_tkernel::message::ProgressRange;
use rustycad_tkernel::ncollection::{DataMap, List};
use rustycad_tkernel::standard::Failure;
use rustycad_tkg3d::top_abs::{Orientation, ShapeEnum};
use rustycad_tktopalgo::brep_builder_api::BRepBuilderAPISewing;
use rustycad_tktopalgo::brep_lib;

impl BiTgteBlend {
    /// The single shape bound to `(S, F)` in `myCreated`.
    fn created_on(&self, s: &Shape, f: &Shape) -> Option<Shape> {
        self.my_created
            .seek(s)
            .and_then(|m| m.seek(f))
            .and_then(|l| l.first().cloned())
    }

    /// Binds `[image]` to `(S, F)` in `myCreated`, the map of `S` reset to empty when
    /// `reset` (a `Bind(S, EmptyMap)` natively).
    fn bind_created(&mut self, s: &Shape, f: &Shape, image: Shape, reset: bool) {
        if reset || !self.my_created.is_bound(s) {
            self.my_created.bind(s.clone(), DataMap::default());
        }
        if let Some(m) = self.my_created.change_seek(s) {
            let mut l = List::default();
            l.append(image);
            m.bind(f.clone(), l);
        }
    }

    /// `ComputeShape()`: the edges kept by the unwinding recorded in `myCreated`, then
    /// the untouched faces and the faces of the shape rebuilt on their unwound offsets
    /// (sharing the edges and vertices created on the supports) added to `myResult`,
    /// which is sewn.
    pub fn compute_shape(&mut self) -> Result<(), Failure> {
        // Find in the initial Shapel:
        //  - untouched Faces
        //  - generated tubes
        //  - the faces neighbors of tubes that should be reconstructed preserving sharing.
        let b = BRepBuilder::default();

        // Maj of the Map of created.
        // Update edges that do not change in the resulting shape
        // i.e. invariant edges in the unwinding.
        let shape = self.my_shape.clone();
        for cur_f in Explorer::new(&shape, ShapeEnum::Face, ShapeEnum::Shape)? {
            if !self.my_faces.contains(&cur_f) {
                continue; // so the face is not touched
            }

            // so the faces are unwinded
            let Some(offset) = self.my_map_sf.seek(&cur_f).cloned() else {
                continue; // inverted or degenerated
            };

            let cur_of = offset.face().clone();

            if !self.my_image_offset.has_image(&cur_of) {
                // face disappears in unwinding
                continue;
            }

            for cur_e in Explorer::new(&cur_f, ShapeEnum::Edge, ShapeEnum::Shape)? {
                let cur_oe = topods::edge(&offset.generated(&cur_e))?;

                if !self.my_image_offset.has_image(&cur_oe) {
                    continue;
                }
                // CurOE disappears

                let im_e = self
                    .my_image_offset
                    .image(&cur_oe)
                    .first()
                    .cloned()
                    .ok_or_else(|| {
                        Failure::with_message("Standard_NoSuchObject", "NCollection_List::First")
                    })?;
                if im_e.is_same(&cur_oe) {
                    self.bind_created(&cur_oe, &cur_f, cur_e.clone(), true);
                }
            }
        }

        // The connected faces are already in myResult.
        // So it is necessary to add faces:
        //    - non-touched (so not in myFaces)
        //    - issuing from the unwinding (non degenerated, non inverted, non disappeared)
        for cur_f in Explorer::new(&shape, ShapeEnum::Face, ShapeEnum::Shape)? {
            let cur_f = topods::face(&cur_f)?;

            if !self.my_faces.contains(&cur_f) {
                // so the face is not touched
                b.add(&mut self.my_result, &cur_f)?;
                continue;
            }
            // so the faces are unwindeds

            let Some(cur_of) = self.my_map_sf.seek(&cur_f).map(|of| of.face().clone()) else {
                continue; // inverted or degenerated
            };

            if !self.my_image_offset.has_image(&cur_of) {
                // face disappears in unwinding
                continue;
            }

            // List of faces generated by a face in the unwinding
            let lim = self.my_image_offset.last_image(&cur_of);
            for debouc in &lim {
                // DeboucFace = offset Face unwinded in "Debouc".
                let debouc_face = topods::face(debouc)?;
                let new_f = self.rebuilt_face(&cur_f, &debouc_face, &b)?;
                b.add(&mut self.my_result, &new_f)?;
            }
        }

        // non-regarding the cause, there always remain greeb borders on this Shape, so it is sewn.
        let mut sew = BRepBuilderAPISewing::new(self.my_tol, true, true, true, false);

        brep_lib::build_curves3d_default(&self.my_result)?;

        for f in Explorer::new(&self.my_result, ShapeEnum::Face, ShapeEnum::Shape)? {
            sew.add(&f)?;
        }

        sew.perform(&ProgressRange::default())?;

        // SameParameter is done in case Sew does not do it (Detect that the edges
        // are not sameparameter but does nothing.)
        let sewed_shape = sew.sewed_shape().clone();
        if !sewed_shape.is_null() {
            for sec in Explorer::new(&sewed_shape, ShapeEnum::Edge, ShapeEnum::Shape)? {
                let sec = topods::edge(&sec)?;
                brep_lib::same_parameter_edge(&sec, BRepTool::edge_tolerance(&sec)?)?;
            }
            self.my_result = sewed_shape;
        }
        Ok(())
    }

    /// The face of the shape rebuilt on the boundary of its unwound offset: the edges
    /// are the created ones, or new edges with the p-curves of the unwound face (and new
    /// vertices on the surface of the face), shared through `myCreated`.
    fn rebuilt_face(
        &mut self,
        cur_f: &Face,
        debouc_face: &Face,
        b: &BRepBuilder,
    ) -> Result<Face, Failure> {
        let (s, l) = BRepTool::surface_with_location(cur_f)?;
        let surface = live(&s, "surface")?;

        let mut new_f = Face::default();
        b.make_face(&mut new_f);
        b.update_face(&new_f, &s, &l, BRepTool::face_tolerance(cur_f)?)?;

        let mut map_ss: DataMap<Shape, Shape, ShapeMapHasher> = DataMap::default();

        let face = topods::face(&debouc_face.oriented(Orientation::Forward))?;
        for e in Explorer::new(&face, ShapeEnum::Edge, ShapeEnum::Shape)? {
            let e = topods::edge(&e)?;
            let (v1, v2) = topexp::vertices(&e, false);
            if let Some(oe) = self.created_on(&e, cur_f) {
                let (ov1, ov2) = topexp::vertices(&topods::edge(&oe)?, false);
                for (v, ov) in [(&v1, ov1), (&v2, ov2)] {
                    if !self.my_created.is_bound(v) {
                        self.my_created
                            .bind(v.clone().into_shape(), DataMap::default());
                    }
                    if self.created_on(v, cur_f).is_none()
                        && !self.my_created.seek(v).is_some_and(|m| m.is_bound(cur_f))
                    {
                        self.bind_created(v, cur_f, ov.into_shape(), false);
                    }
                }
            }
        }

        for w in Explorer::new(&face, ShapeEnum::Wire, ShapeEnum::Shape)? {
            let w = topods::wire(&w)?;
            let mut ow = Wire::default();
            b.make_wire(&mut ow);

            for e in Explorer::new(
                &w.oriented(Orientation::Forward),
                ShapeEnum::Edge,
                ShapeEnum::Shape,
            )? {
                let e = topods::edge(&e)?;
                let c2d = BRepTool::curve_on_face(&e, &face)?;
                let (f, l2) = (c2d.first, c2d.last);
                let mut oe: Edge;
                if let Some(cut) = map_ss.seek(&e) {
                    // this is an edge of cutting
                    oe = topods::edge(cut)?;
                    let c2d_1 = BRepTool::curve_on_face(&topods::edge(&e.reversed())?, &face)?;
                    if e.orientation() == Orientation::Forward {
                        b.update_edge_pcurves_on_face(
                            &oe,
                            (&c2d.pcurve, &c2d_1.pcurve),
                            &new_f,
                            BRepTool::edge_tolerance(&e)?,
                        )?;
                    } else {
                        b.update_edge_pcurves_on_face(
                            &oe,
                            (&c2d_1.pcurve, &c2d.pcurve),
                            &new_f,
                            BRepTool::edge_tolerance(&e)?,
                        )?;
                    }
                    b.range(&oe, c2d_1.first, c2d_1.last, false)?;
                } else {
                    // Is there an image in the Map of Created ?
                    if self.my_created.is_bound(&e) {
                        oe = match self.created_on(&e, cur_f) {
                            Some(created) => topods::edge(&created)?,
                            None => Edge::default(),
                        };
                    } else {
                        oe = Edge::default();
                        b.make_edge(&mut oe)?;
                        let (v1, v2) = topexp::vertices(&e, false);
                        let new_vertex = |v: &Vertex, this: &mut Self| -> Result<Vertex, Failure> {
                            if let Some(ov) = this.created_on(v, cur_f) {
                                return topods::vertex(&ov);
                            }
                            let mut ov = Vertex::default();
                            b.make_vertex(&mut ov);
                            let p2d = live(&c2d.pcurve, "pcurve")?
                                .value(BRepTool::parameter_on_face(v, &e, &face)?)?;
                            let p = surface
                                .value(p2d.x(), p2d.y())?
                                .transformed(l.transformation());
                            b.update_vertex_point(&ov, p, BRepTool::vertex_tolerance(v)?)?;
                            this.bind_created(v, cur_f, ov.clone().into_shape(), true);
                            Ok(ov)
                        };
                        let ov1 = new_vertex(&v1, self)?;
                        let ov2 = new_vertex(&v2, self)?;
                        b.add(&mut oe, &ov1.oriented(v1.orientation()))?;
                        b.add(&mut oe, &ov2.oriented(v2.orientation()))?;
                    }
                    b.update_edge_pcurve_on_face(
                        &oe,
                        &c2d.pcurve,
                        &new_f,
                        BRepTool::edge_tolerance(&e)?,
                    )?;
                    b.range(&oe, f, l2, false)?;
                    map_ss.bind(e.clone().into_shape(), oe.clone().into_shape());
                }
                b.add(&mut ow, &oe.oriented(e.orientation()))?;
            }
            b.add(&mut new_f, &ow.oriented(w.orientation()))?;
        }

        new_f.set_orientation(debouc_face.orientation());

        brep_tools::update(&new_f)?;
        Ok(new_f)
    }
}
