"""Compile OIT outputs for fill shaders; nodal lines, markers and glyphs stay ordered."""
from pathlib import Path
from vulkan_surface_texture_shaders import ShaderRunner, surface_shader_variants
from vulkan_fixed_lighting_shaders import fixed_lighting_shader_variants
from vulkan_mesh_edge_shaders import mesh_edge_shader_variants

OitShaderVariant = tuple[str, str, tuple[str, ...]]


def oit_fill_shader_variants() -> tuple[OitShaderVariant, ...]:
    """Enumerate actual fill interfaces; oit_fill_shader_variants()."""
    variants: list[OitShaderVariant] = []
    for family in ("unlit", "lighting"):
        for clipped in (False, True):
            variants.append((family + (".clipped" if clipped else ""), family + ".frag",
                             ("-DMARTENSITE_CLIPPING=1",) if clipped else ()))
    variants.extend((stem, "surface.frag", flags) for stem, flags in surface_shader_variants())
    variants.extend((stem, "surface.frag", flags) for stem, stage, flags in
                    mesh_edge_shader_variants() if stage == "frag")
    variants.extend((stem, "surface.frag" if stem.startswith("surface") else "lighting.frag", flags)
                    for stem, stage, flags in fixed_lighting_shader_variants()
                    if stage == "frag" and not any(part in stem.split(".") for part in ("line", "point")))
    return tuple(variants)


def oit_geometry_shader_variants() -> tuple[OitShaderVariant, ...]:
    """Keep initial peeling distinct from three-output peeling; oit_geometry_shader_variants()."""
    variants: list[OitShaderVariant] = []
    modes = (("weighted", ("-DMARTENSITE_OIT_WEIGHTED=1",)),
             ("initial", ("-DMARTENSITE_OIT_PEELING=1", "-DMARTENSITE_OIT_INITIAL=1")),
             ("peeling", ("-DMARTENSITE_OIT_PEELING=1",)))
    for stem, source, flags in oit_fill_shader_variants():
        for mode, defines in modes:
            for fixed in (False, True):
                fixed_flags = ("-DMARTENSITE_OIT_FIXED_OUTPUT=1",) if fixed else ()
                name = stem + ".oit." + mode + (".fixed-output" if fixed else "")
                variants.append((name, source, flags + defines + fixed_flags))
    return tuple(variants)


def oit_composite_shader_variants() -> tuple[OitShaderVariant, ...]:
    """Expose sample-ID compositor variants; oit_composite_shader_variants()."""
    return (("oit_composite.vert", "oit_composite.vert", ()),
            ("oit.weighted", "oit_composite.frag", ()),
            ("oit.weighted.msaa", "oit_composite.frag", ("-DMARTENSITE_OIT_MSAA=1",)),
            ("oit.peeling", "oit_composite.frag", ("-DMARTENSITE_OIT_PEELING=1",)),
            ("oit.back", "oit_composite.frag", ("-DMARTENSITE_OIT_BACK_BLEND=1",)))


def compile_oit_shaders(root: Path, folder: Path, env: dict[str, str], runner: ShaderRunner) -> None:
    """Compile every actual output layout; compile_oit_shaders(root, tmp, env, run)."""
    shaders = root / "crates/vulkan/shaders"
    for stem, source, flags in oit_geometry_shader_variants() + oit_composite_shader_variants():
        name = stem + (".spv" if source.endswith(".vert") else ".frag.spv")
        runner(["glslangValidator", *flags, "--target-env", "vulkan1.3", "-V",
                str(shaders / source), "-o", str(folder / name)], env)


def oit_shader_table_source() -> str:
    """Generate package-owned static shader bytes; oit_shader_table_source()."""
    variants = oit_geometry_shader_variants()
    lines = ["// Generated by tools/vulkan_oit_shaders.py; never load shader files at runtime.",
             "macro_rules! oit_fragment {",
             "    ($stem:literal) => {",
             '        ($stem, include_bytes!(concat!("../../shaders/", $stem, ".frag.spv")).as_slice())',
             "    };", "}",
             f"pub(super) const OIT_FRAGMENTS: [(&str, &[u8]); {len(variants)}] = ["]
    lines.extend(f'    oit_fragment!("{stem}"),'
                 for stem, _, _ in variants)
    return "\n".join(lines + ["];", ""])
