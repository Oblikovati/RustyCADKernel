#!/usr/bin/env python3
"""Carry the PLib_JacobiPolynomial tables over from the pinned OCCT sources verbatim.

Usage: python3 tools/generate_plib_jacobi_tables.py --source ../OCCT [--check]

Every literal is copied as text, so the Rust compiler rounds exactly the decimal
strings the C++ compiler rounds. The per-degree coefficient arrays of
PLib_JacobiPolynomial_Coeffs.pxx are prefixes of their degree-30 array; the script
proves this before emitting only the degree-30 arrays.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT/'crates/tkmath/src/plib'
PACKAGE = 'src/FoundationClasses/TKMath/PLib'
CHUNK = 480
LITERAL = re.compile(r'static constexpr double (\w+)(\[[^=]*\])\s*=\s*(\{.*?\});', re.S)


def parse_tables(text: str) -> dict[str, list[str]]:
    """Map each constexpr array name to its literal strings; parse_tables(pxx_text)."""
    tables = {}
    for name, shape, body in LITERAL.findall(text):
        # TransMatrix rows carry `// TransMatrix_Cn[1][0]` markers between literals.
        body = re.sub(r'//[^\n]*', ' ', body)
        values = [token.strip() for token in re.sub(r'[{}]', ' ', body).split(',') if token.strip()]
        sizes = [int(size) for size in re.findall(r'\[(\d+)\]', shape)]
        expected = 1
        for size in sizes: expected *= size
        if sizes and expected != len(values):
            raise ValueError(f'{name}: {len(values)} literals; expected {expected} from {shape}')
        tables[name] = values
    return tables


def degree30_coefficients(tables: dict[str, list[str]]) -> dict[str, list[str]]:
    """Prove the prefix property and keep degree-30 arrays; degree30_coefficients(tables)."""
    selected = {}
    for kind in ['TNorm', 'CofA', 'CofB', 'Denom']:
        for level in range(3):
            full = tables[f'{kind}_C{level}_D30']
            for degree in range(31):
                partial = tables[f'{kind}_C{level}_D{degree}']
                if [float(v) for v in partial] != [float(v) for v in full[:degree+1]]:
                    raise ValueError(f'{kind}_C{level}_D{degree} is not a prefix of degree 30')
            selected[f'{kind}_C{level}'] = full
    return selected


def rust_name(name: str) -> str:
    """Convert a native table name to a Rust constant; rust_name('WeightsDB0_C1')."""
    spaced = re.sub(r'(?<=[a-z0-9])(?=[A-Z])', '_', name.replace('DB', 'Db'))
    return spaced.upper()


def fragments(name: str, values: list[str]) -> dict[str, str]:
    """Split one table into include!-able array fragments; fragments('X', values)."""
    files = {}
    for index in range(0, len(values), CHUNK):
        body = ''.join(f'    {value},\n' for value in values[index:index+CHUNK])
        files[f'{rust_name(name).lower()}_{index//CHUNK}.rs'] = f'&[\n{body}]\n'
    return files


def index_module(tables: dict[str, list[str]], files: dict[str, str]) -> str:
    """Emit the constant index over the fragments; index_module(tables, files)."""
    lines = [INDEX_PRELUDE]
    for name in tables:
        stem = rust_name(name).lower()
        includes = ''.join(f'        include!("jacobi_tables/{file}"),\n' for file in sorted(files, key=chunk_order) if file.rsplit('_', 1)[0] == stem)
        lines.append(f'/// Verbatim `{name}` literals ({len(tables[name])} values).\n'
                     f'pub(super) const {rust_name(name)}: ChunkedTable = ChunkedTable {{\n'
                     f'    chunks: &[\n{includes}    ],\n}};\n')
    return '\n'.join(lines)


def chunk_order(file: str) -> tuple[str, int]:
    """Sort fragments by table then numeric chunk; chunk_order('a_10.rs')."""
    stem, index = file[:-3].rsplit('_', 1)
    return stem, int(index)


INDEX_PRELUDE = '''//! Jacobi tables generated by tools/generate_plib_jacobi_tables.py; do not edit.
//!
//! The literals come verbatim from PLib_JacobiPolynomial_Data.pxx and
//! PLib_JacobiPolynomial_Coeffs.pxx at 3d097a0328e71b826377d4814ab05ec3c3d23871.
#![allow(clippy::excessive_precision)]

/// Fixed-size fragments of one flattened native table.
pub(super) struct ChunkedTable {
    chunks: &'static [&'static [f64]],
}
impl ChunkedTable {
    /// Returns the flattened entry, or `None` past the native array end; `TABLE.get(0)`.
    pub(super) fn get(&self, index: usize) -> Option<f64> {
        self.chunks.get(index / CHUNK)?.get(index % CHUNK).copied()
    }
    /// Counts the flattened entries; `TABLE.len()`.
    pub(super) fn len(&self) -> usize {
        self.chunks.iter().map(|chunk| chunk.len()).sum()
    }
}
const CHUNK: usize = '''+str(CHUNK)+''';
'''


def generate(source: Path) -> dict[Path, str]:
    """Render every generated file; generate(Path('../OCCT'))."""
    data_text = (source/PACKAGE/'PLib_JacobiPolynomial_Data.pxx').read_text()
    coeffs_text = (source/PACKAGE/'PLib_JacobiPolynomial_Coeffs.pxx').read_text()
    tables = parse_tables(data_text)
    tables.update(degree30_coefficients(parse_tables(coeffs_text)))
    files = {}
    for name, values in tables.items():
        files.update(fragments(name, values))
    output = {TARGET/'jacobi_tables'/name: text for name, text in files.items()}
    output[TARGET/'jacobi_tables.rs'] = index_module(tables, files)
    return output


def main() -> int:
    """Write or check the generated tables; exit 1 when --check finds drift."""
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, default=ROOT/'../OCCT')
    parser.add_argument('--check', action='store_true')
    arguments = parser.parse_args()
    output = generate(arguments.source.resolve())
    stale = [path for path, text in output.items() if not path.exists() or path.read_text() != text]
    if arguments.check:
        for path in stale: print(f'stale generated table: {path.relative_to(ROOT)}')
        return 1 if stale else 0
    (TARGET/'jacobi_tables').mkdir(parents=True, exist_ok=True)
    for path in stale: path.write_text(output[path])
    print(f'{len(output)} files, {len(stale)} written')
    return 0


if __name__ == '__main__':
    sys.exit(main())
