//! OCC24537: literal upstream byte references on little-endian platforms.
#![allow(non_snake_case, clippy::approx_constant)]
use rustycad_tkernel::fsd::BinaryFile;

#[test]
fn FSD_BinaryFileTest__OCC24537_InverseInt_Sequential() {
    let inputs: [i32; 10] = [1, 2, 3, 4, 5, 6, 7, 8, 9, 0];
    let expected: &[u8] = &[
        0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x03, 0x00, 0x00, 0x00,
        0x04, 0x00, 0x00, 0x00, 0x05, 0x00, 0x00, 0x00, 0x06, 0x00, 0x00, 0x00, 0x07, 0x00, 0x00,
        0x00, 0x08, 0x00, 0x00, 0x00, 0x09, 0x00, 0x00, 0x00, 0x00,
    ];
    let actual: Vec<u8> = inputs
        .into_iter()
        .flat_map(|value| BinaryFile::inverse_int(value).to_ne_bytes())
        .collect();
    assert_eq!(actual, expected);
}

