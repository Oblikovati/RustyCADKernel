/// The map of the faces generated by each section edge.
pub type GeneratedFaces = DataMap<Shape, List<Shape>, ShapeMapHasher>;

/// Computes a shell of ruled surfaces through generating wires
/// (`BRepFill_Generator`); the wires must have the same number of edges.
///
/// ```ignore
/// let mut generator = BRepFillGenerator::new();
/// generator.add_wire(&wire1);
/// generator.add_wire(&wire2);
/// generator.perform()?;
/// let shell = generator.shell();
/// ```
pub struct BRepFillGenerator {
    my_wires: Vec<Shape>,
    my_shell: Shell,
    my_map: GeneratedFaces,
    my_old_new_shapes: DataMap<Shape, Shape, ShapeMapHasher>,
    my_reshaper: BRepToolsReShape,
    my_mutable_input: bool,
    my_status: ThruSectionErrorStatus,
}

impl Default for BRepFillGenerator {
    fn default() -> Self {
        Self::new()
    }
}

impl BRepFillGenerator {
    /// `BRepFill_Generator()`: no wire, a mutable input and the NotDone status;
    /// `BRepFillGenerator::new()`.
    pub fn new() -> Self {
        Self {
            my_wires: Vec::new(),
            my_shell: Shell::default(),
            my_map: GeneratedFaces::default(),
            my_old_new_shapes: DataMap::default(),
            my_reshaper: BRepToolsReShape::new(),
            my_mutable_input: true,
            my_status: ThruSectionErrorStatus::NotDone,
        }
    }

    /// `AddWire(Wire)`: appends a section; `generator.add_wire(&wire)`.
    pub fn add_wire(&mut self, wire: &Wire) {
        self.my_wires.push(wire.as_ref().clone());
    }

    /// `Shell()`: the computed shell (null before `perform`); `generator.shell()`.
    pub fn shell(&self) -> &Shell {
        &self.my_shell
    }

    /// `Generated()`: the faces created from each section edge; `generator.generated()`.
    pub fn generated(&self) -> &GeneratedFaces {
        &self.my_map
    }

    /// `GeneratedShapes(SSection)`: the faces created from a sub-shape of a section,
    /// an empty list when there is none; `generator.generated_shapes(&edge)`.
    pub fn generated_shapes(&self, section: &Shape) -> &List<Shape> {
        static EMPTY: OnceLock<List<Shape>> = OnceLock::new();
        match self.my_map.seek(section) {
            Some(faces) => faces,
            None => EMPTY.get_or_init(List::default),
        }
    }

    /// `ResultShape(theShape)`: the shape that replaces `theShape` in the shell (the
    /// copy of an input edge or wire, followed through the re-shaper), the shape
    /// itself when it is unchanged; `generator.result_shape(&edge)?`.
    pub fn result_shape(&self, shape: &Shape) -> Result<Shape, Failure> {
        let mut new_shape: Shape = match self.my_old_new_shapes.seek(shape) {
            Some(found) => found.clone(),
            None => shape.clone(),
        };
        loop {
            let previous: Shape = new_shape.clone();
            new_shape = self.my_reshaper.value(&new_shape)?;
            if new_shape == previous {
                return Ok(new_shape);
            }
        }
    }

    /// `SetMutableInput(theIsMutableInput)`: whether the input profiles may be
    /// modified (default true); `generator.set_mutable_input(false)`.
    pub fn set_mutable_input(&mut self, is_mutable_input: bool) {
        self.my_mutable_input = is_mutable_input;
    }

    /// `IsMutableInput()`: the mutable input state; `generator.is_mutable_input()`.
    pub fn is_mutable_input(&self) -> bool {
        self.my_mutable_input
    }

    /// `GetStatus()`: the status of the last `perform`; `generator.get_status()`.
    pub fn get_status(&self) -> ThruSectionErrorStatus {
        self.my_status
    }
}
