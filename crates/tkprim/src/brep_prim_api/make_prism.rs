use rustycad_tktopalgo::brep_lib;

/// `check(S)`: builds the missing 3d curves of the edges of `shape`
/// (`BRepLib::BuildCurves3d`, its answer ignored) before the sweep reads them.
pub(crate) fn check(shape: &Shape) -> Result<&Shape, Failure> {
    brep_lib::build_curves3d_default(shape)?;
    Ok(shape)
}

/// `BRepPrimAPI_MakePrism`: the prism of a shape along a vector, or the infinite (or
/// semi-infinite) prism along a direction; the constructors build it
/// (docs/prim-design.md section 4).
///
/// ```
/// use rustycad_tkbrep::topods::Shape;
/// use rustycad_tkmath::gp::{Point3, Vector3};
/// use rustycad_tkprim::brep_prim_api::BRepPrimAPIMakePrism;
/// use rustycad_tktopalgo::brep_builder_api::{BRepBuilderAPIMakeShape, BRepBuilderAPIMakeVertex};
/// let vertex: Shape = BRepBuilderAPIMakeVertex::new(Point3::new(0.0, 0.0, 0.0))?.vertex()?.into();
/// let mut maker = BRepPrimAPIMakePrism::new(&vertex, Vector3::new(0.0, 0.0, 1.0), false, true)?;
/// assert!(maker.is_done());
/// assert!(!maker.shape()?.is_null());
/// # Ok::<(), rustycad_tkernel::standard::Failure>(())
/// ```
pub struct BRepPrimAPIMakePrism {
    base: BRepBuilderAPIMakeShapeBase,
    my_prism: BRepSweepPrism,
}

impl BRepPrimAPIMakePrism {
    /// The maker of `my_prism`, built.
    fn built(my_prism: BRepSweepPrism) -> Result<Self, Failure> {
        let mut maker = Self {
            base: BRepBuilderAPIMakeShapeBase::new(),
            my_prism,
        };
        maker.build(&ProgressRange::default())?;
        Ok(maker)
    }

    /// `BRepPrimAPI_MakePrism(S, V, Copy = false, Canonize = true)`: the prism of `shape`
    /// along `vector`; Standard_ConstructionError for a vector not longer than
    /// Precision::Confusion(); `BRepPrimAPIMakePrism::new(&shape, v, false, true)?`.
    pub fn new(
        shape: &Shape,
        vector: Vector3,
        copy: bool,
        canonize: bool,
    ) -> Result<Self, Failure> {
        Self::built(BRepSweepPrism::new(check(shape)?, vector, copy, canonize)?)
    }

    /// `BRepPrimAPI_MakePrism(S, D, Inf = true, Copy = false, Canonize = true)`: the
    /// infinite prism of `shape` along `direction` (semi-infinite toward it unless
    /// `inf`); `BRepPrimAPIMakePrism::infinite(&shape, d, true, false, true)?`.
    pub fn infinite(
        shape: &Shape,
        direction: Direction3,
        inf: bool,
        copy: bool,
        canonize: bool,
    ) -> Result<Self, Failure> {
        Self::built(BRepSweepPrism::infinite(
            check(shape)?,
            direction,
            inf,
            copy,
            canonize,
        )?)
    }

    /// `Prism()`: the sweep algorithm; `maker.prism()`.
    pub fn prism(&self) -> &BRepSweepPrism {
        &self.my_prism
    }

    /// `FirstShape(theShape)`: the bottom shape generated by a sub-shape of the base;
    /// `maker.first_shape_of(&edge)?`.
    pub fn first_shape_of(&mut self, shape: &Shape) -> Result<Shape, Failure> {
        self.my_prism.first_shape_of(shape)
    }

    /// `LastShape(theShape)`: the top shape generated by a sub-shape of the base;
    /// `maker.last_shape_of(&edge)?`.
    pub fn last_shape_of(&mut self, shape: &Shape) -> Result<Shape, Failure> {
        self.my_prism.last_shape_of(shape)
    }
}

impl BRepBuilderAPIMakeShape for BRepPrimAPIMakePrism {
    fn make_shape_base(&self) -> &BRepBuilderAPIMakeShapeBase {
        &self.base
    }

    fn make_shape_base_mut(&mut self) -> &mut BRepBuilderAPIMakeShapeBase {
        &mut self.base
    }

    /// `Build()`: the prism becomes the shape and the maker is done.
    fn build(&mut self, _range: &ProgressRange<'_>) -> Result<(), Failure> {
        self.base.my_shape = self.my_prism.shape()?;
        self.base.set_done();
        Ok(())
    }

    /// `Generated(S)`: the shape generated by `S` when both it and the base shape of `S`
    /// are in the prism, else nothing.
    fn generated(&mut self, shape: &Shape) -> Result<&List<Shape>, Failure> {
        self.base.my_generated.clear();
        if self.my_prism.is_used(shape)? && self.my_prism.gen_is_used(shape)? {
            let generated = self.my_prism.shape_of(shape)?;
            self.base.my_generated.append(generated);
        }
        Ok(&self.base.my_generated)
    }

    /// `IsDeleted(S)`: no shape generated by `S` is in the prism.
    fn is_deleted(&mut self, shape: &Shape) -> Result<bool, Failure> {
        Ok(!self.my_prism.is_used(shape)?)
    }
}

impl BRepPrimAPIMakeSweep for BRepPrimAPIMakePrism {
    fn first_shape(&mut self) -> Result<Shape, Failure> {
        self.my_prism.first_shape()
    }

    fn last_shape(&mut self) -> Result<Shape, Failure> {
        self.my_prism.last_shape()
    }
}
