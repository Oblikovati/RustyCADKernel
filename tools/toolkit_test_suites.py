#!/usr/bin/env python3
"""Keep every Martensite integration test in a toolkit suite or isolated target.

Example: python3 tools/toolkit_test_suites.py --write
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path
import tomllib

INDEX_SIZE = 128


def suite_sources(manifest: Path) -> list[Path]:
    """Find cases not explicitly isolated; suite_sources(Path('crates/tkernel/Cargo.toml'))."""
    configuration = tomllib.loads(manifest.read_text())
    targets = configuration.get("test", [])
    isolated = {target["path"] for target in targets if target["name"] != "toolkit"}
    for source in isolated:
        if not (manifest.parent / source).is_file():
            raise ValueError(f"Isolated source {source!r}: expected existing test file")
    directory = manifest.parent / "tests"
    candidates = [*directory.glob("*.rs"), *directory.glob("*/main.rs")]
    return sorted(
        source
        for source in candidates
        if source.name != "toolkit.rs"
        and source.relative_to(manifest.parent).as_posix() not in isolated
    )


def implicit_case_children(source: Path) -> list[str]:
    """Select top-level implicit modules, preserving inline wrappers; implicit_case_children(Path('case.rs'))."""
    pattern = r"(?m)^(?P<attributes>(?:#\[[^\]]*\]\s*\n|//[^\n]*\n|\n)*)(?:pub(?:\([^)]*\))?\s+)?mod\s+(?P<name>[A-Za-z_][A-Za-z0-9_]*)\s*;"
    declarations = re.finditer(pattern, source.read_text())
    return [
        match["name"] for match in declarations if "#[path" not in match["attributes"]
    ]


def nested_root_case(source: Path) -> bool:
    """Keep implicit Rust child-module roots conventional; nested_root_case(Path('tests/roots.rs'))."""
    directory = source.with_suffix("")
    if source.name == "main.rs" or not directory.is_dir():
        return False
    return any(
        (directory / f"{name}.rs").is_file() or (directory / name / "mod.rs").is_file()
        for name in implicit_case_children(source)
    )


def suite_indexes(sources: list[Path]) -> dict[str, str]:
    """Bound flat case indexes without rewriting child-module paths; suite_indexes([Path('case.rs')])."""
    indexes: dict[str, str] = {}
    for offset in range(0, len(sources), INDEX_SIZE):
        name = f"suites/cases_{offset // INDEX_SIZE:02}.rs"
        indexes[name] = (
            "// Generated by tools/toolkit_test_suites.py; preserve case files.\n"
            + "".join(
                f'#[path = "../{source.relative_to(source.parents[1] if source.name == "main.rs" else source.parent).as_posix()}"]\n'
                f'pub mod {source.parent.name if source.name == "main.rs" else source.stem};\n'
                for source in sources[offset : offset + INDEX_SIZE]
            )
        )
    return indexes


def suite_contents(sources: list[Path]) -> dict[str, str]:
    """Retain conventional child-module resolution and case identity; suite_contents([Path('a.rs')])."""
    direct = [source for source in sources if nested_root_case(source)]
    indexes = suite_indexes([source for source in sources if source not in direct])
    root = (
        "//! One executable per toolkit keeps repeated linkage out of Martensite tests.\n"
        "#![allow(clippy::module_inception, clippy::duplicate_mod)] // Preserve case identity and fixture isolation.\n"
    )
    # An explicit #[path] changes implicit child lookup; direct roots preserve Rust's module directory.
    root += "".join(f"mod {source.stem};\n" for source in direct)
    indexes["toolkit.rs"] = root + "".join(f'include!("{name}");\n' for name in indexes)
    return indexes


def synchronize_suite(manifest: Path, write: bool) -> list[str]:
    """Reject missing and stale cases, or regenerate; synchronize_suite(manifest, False)."""
    expected = suite_contents(suite_sources(manifest))
    directory = manifest.parent / "tests"
    obsolete = set(directory.glob("suites/*.rs")) - {
        directory / name for name in expected
    }
    mismatches = [str(path) for path in obsolete]
    for name, contents in expected.items():
        path = directory / name
        if path.exists() and path.read_text() == contents:
            continue
        mismatches.append(str(path))
        if write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents)
    if write:
        for path in obsolete:
            path.unlink()
    return mismatches


def configured_suite_manifests(root: Path) -> list[Path]:
    """Reject unconsolidated new toolkit tests; configured_suite_manifests(root)."""
    selected: list[Path] = []
    for manifest in sorted((root / "crates").glob("*/Cargo.toml")):
        configuration = tomllib.loads(manifest.read_text())
        if configuration["package"].get("autotests", True):
            if suite_sources(manifest):
                raise ValueError(
                    f"Test manifest {str(manifest)!r}: expected autotests=false and a toolkit target"
                )
            continue
        if not any(
            target["name"] == "toolkit" for target in configuration.get("test", [])
        ):
            raise ValueError(
                f"Test manifest {str(manifest)!r}: expected an explicit toolkit target"
            )
        selected.append(manifest)
    return selected


def main() -> int:
    """Check test discovery before CI compiles; main()."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    arguments = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    mismatches: list[str] = []
    for manifest in configured_suite_manifests(root):
        mismatches.extend(synchronize_suite(manifest, arguments.write))
    if mismatches and not arguments.write:
        parser.error(
            f"Stale toolkit suites {mismatches!r}; expected --write regeneration"
        )
    print("Toolkit test discovery includes every integration-test source.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
