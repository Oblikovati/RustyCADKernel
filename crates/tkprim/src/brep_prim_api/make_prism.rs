//! `BRepPrimAPI_MakePrism`: the maker of linear sweeps.
use super::make_sweep::BRepPrimAPIMakeSweep;
use crate::brep_sweep::BRepSweepPrism;
use rustycad_tkbrep::topods::Shape;
use rustycad_tkernel::message::ProgressRange;
