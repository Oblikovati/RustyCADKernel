"""Render the parity metrics document as a Markdown report.

Example: `metrics_markdown(build_metrics(paths))` returns the text of `METRICS.md`.
"""

from __future__ import annotations

from collections.abc import Mapping

_SCOPE_ORDER = ("port", "replaced", "excluded", "undecided")
_HEADER = (
    "| Toolkit | API decl. | Done | Done % | Partial | Unverified claim | Open gap | "
    "Boilerplate done % | Ledger defects | GTests mapped | GTests unmapped | GTests n/a |\n"
    "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n"
)
_INTRO = """# OCCT parity metrics

Generated by `tools/api_metrics_report.py` from the published crosswalk; do not edit by hand.

- **API decl.**: OCCT declarations that need Rust code or a reasoned exclusion, owned by the
  toolkit of their header. Boilerplate (allocation, RTTI and exception macro expansions,
  destructors, copy/move constructors, assignment) is counted apart.
- **Done**: verified implemented + excluded with a reason + upstream unimplemented.
- **Unverified claim**: a ledger row claims the declaration, but its Rust target does not resolve.
- **Open gap**: unclaimed or unverified API declarations.
- **Ledger defects**: rows that match no C++ declaration or no Rust item.
- **GTests n/a**: upstream GTests of a C++-only language property (for example "not movable");
  the native test still runs, and the row states why no Rust test can check it.
"""


def metrics_markdown(metrics: Mapping[str, object]) -> str:
    """Whole report: the scope totals, then one table per scope."""
    parts = [_INTRO, _totals_section(metrics["totals_by_scope"])]
    toolkits = metrics["toolkits"]
    for scope in _SCOPE_ORDER:
        names = [name for name, value in toolkits.items() if value["scope"] == scope]
        if names:
            parts.append(_scope_section(scope, names, toolkits))
    return "\n".join(parts)


def _totals_section(totals: Mapping[str, Mapping[str, int]]) -> str:
    lines = [
        "## Totals by scope\n",
        "| Scope | Toolkits | API decl. | Done | Partial | Open gap | GTests mapped | GTests unmapped | GTests n/a |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for scope in _SCOPE_ORDER:
        if scope in totals:
            total = totals[scope]
            lines.append(
                f"| {scope} | {total['toolkits']} | {total['api_declarations']} | {total['api_done']} | "
                f"{total['api_partial']} | {total['api_open']} | {total['gtests_mapped']} | "
                f"{total['gtests_unmapped']} | {total['gtests_not_applicable']} |"
            )
    return "\n".join(lines) + "\n"


def _scope_section(scope: str, names: list[str], toolkits: Mapping[str, Mapping]) -> str:
    rows = "".join(_toolkit_row(name, toolkits[name]) for name in names)
    reason = toolkits[names[0]]["scope_reason"]
    note = f"\n{reason}\n" if reason else ""
    return f"## Scope: {scope}\n{note}\n{_HEADER}{rows}"


def _toolkit_row(name: str, metrics: Mapping[str, Mapping]) -> str:
    api, boilerplate = metrics["api"], metrics["boilerplate"]
    defects = sum(metrics["ledger_defects"].values())
    return (
        f"| {name} | {api['declarations']} | {api['done']} | {api['done_percent']} | "
        f"{api['by_status']['partial']} | {api['by_status']['claimed_unverified']} | "
        f"{sum(metrics['open_gap_by_category'].values())} | {boilerplate['done_percent']} | "
        f"{defects} | {metrics['gtests']['mapped']} | {metrics['gtests']['unmapped']} | "
        f"{metrics['gtests']['not_applicable']} |\n"
    )
