"""Additional native compatibility alpha tests preserve original ordinary shader binaries."""
from itertools import product
from pathlib import Path
from vulkan_oit_shaders import oit_fill_shader_variants
from vulkan_fixed_lighting_shaders import fixed_lighting_shader_variants
from vulkan_surface_texture_shaders import ShaderRunner

FragmentAlphaVariant = tuple[str, str, tuple[str, ...]]


def fragment_alpha_variants() -> tuple[FragmentAlphaVariant, ...]:
    """Cover every ordinary fragment interface; fragment_alpha_variants()."""
    variants = list(oit_fill_shader_variants()) + _nodal_fragment_variants()
    variants.extend((stem, stem.split('.')[0] + '.frag', flags)
                    for stem, stage, flags in fixed_lighting_shader_variants()
                    if stage == 'frag' and ('line' in stem or 'point' in stem))
    return tuple(variants)


def _nodal_fragment_variants() -> list[FragmentAlphaVariant]:
    variants: list[FragmentAlphaVariant] = []
    for family, clipped in product(('line', 'point', 'text', 'lighting.line', 'lighting.point'), (False, True)):
        stem = family + ('.clipped' if clipped else '')
        flags = ('-DMARTENSITE_CLIPPING=1',) if clipped else ()
        if family == 'lighting.line': flags += ('-DMARTENSITE_LINE_LIGHTING=1',)
        if family == 'lighting.point': flags += ('-DMARTENSITE_MARKER_LIGHTING=1',)
        variants.append((stem, family.split('.')[0] + '.frag', flags))
    return variants


def compile_fragment_alpha_shaders(root: Path, folder: Path, env: dict[str, str], runner: ShaderRunner) -> None:
    """Compile explicit variants only; compile_fragment_alpha_shaders(root, tmp, env, run)."""
    for stem, source, flags in fragment_alpha_variants():
        runner(['glslangValidator', *flags, '-DMARTENSITE_NATIVE_FRAGMENT_ALPHA=1',
                '--target-env', 'vulkan1.3', '-V', str(root/'crates/vulkan/shaders'/source),
                '-o', str(folder/f'{stem}.native-alpha.frag.spv')], env)


def fragment_alpha_table_source() -> str:
    """Resolve the original static bytes to their matching interface; fragment_alpha_table_source()."""
    lines = ['// Generated by tools/vulkan_fragment_alpha_shaders.py; package-owned shader bytes.',
             'macro_rules! native_alpha_pair {', '    ($stem:literal) => {',
             '        (include_bytes!(concat!("../../shaders/", $stem, ".frag.spv")).as_slice(),',
             '         include_bytes!(concat!("../../shaders/", $stem, ".native-alpha.frag.spv")).as_slice())',
             '    };', '}', 'pub(super) const NATIVE_ALPHA_FRAGMENTS: &[(&[u8], &[u8])] = &[']
    lines.extend(f'    native_alpha_pair!("{stem}"),' for stem, _, _ in fragment_alpha_variants())
    return '\n'.join(lines + ['];', ''])
