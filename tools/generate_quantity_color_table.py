#!/usr/bin/env python3
"""Generate the Rust twin of OCCT's Quantity_ColorTable.pxx and Quantity_NameOfColor.hxx.

The named-color table is data, not code: every sRGB and linear RGB literal is copied
verbatim from the pinned upstream `.pxx` so that Rust's correctly rounded f32 literal
parsing yields the same floats as the C++ `0.522522f` spellings. The enum aliases
(`Quantity_NOC_BLUE1 = Quantity_NOC_BLUE`) become alias constants.

Usage: python3 tools/generate_quantity_color_table.py [--source ../OCCT] [--check]
"""
from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path

from porting import ROOT

PACKAGE = "src/FoundationClasses/TKernel/Quantity"
OUTPUT = ROOT / "crates/tkernel/src/quantity/color_names"
TABLE_CHUNK = 60
CONSTANT_CHUNK = 100
HEADER = """// Generated by tools/generate_quantity_color_table.py from the pinned OCCT sources; do not edit.
"""
RAW_COLOR = re.compile(r"RawColor\(\s*(\w+)\s*,\s*sRGB\s*,\s*0x[0-9A-Fa-f]+\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*,"
                       r"\s*([\d.]+)\s*,\s*RGB\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*\)")


def table_entries(source: Path) -> list[tuple[str, list[str], list[str]]]:
    """`(name, sRGB literals, linear RGB literals)` in table order.

    >>> RAW_COLOR.match('RawColor(RED, sRGB, 0xFF0000, 1.0, 0.0, 0.0, RGB, 1.0, 0.0, 0.0)').group(1)
    'RED'
    """
    text = (source / PACKAGE / "Quantity_ColorTable.pxx").read_text()
    return [(m.group(1), list(m.group(2, 3, 4)), list(m.group(5, 6, 7))) for m in RAW_COLOR.finditer(text)]


def enum_members(source: Path) -> tuple[list[str], list[tuple[str, str]]]:
    """Canonical enumerators in declaration order, and `(alias, target)` pairs."""
    text = (source / PACKAGE / "Quantity_NameOfColor.hxx").read_text()
    body = re.sub(r"//[^\n]*", "", text[text.index("enum Quantity_NameOfColor"):])
    body = body[body.index("{") + 1:body.index("}")]
    canonical: list[str] = []
    aliases: list[tuple[str, str]] = []
    for item in (part.strip() for part in body.split(",")):
        match = re.fullmatch(r"Quantity_NOC_(\w+)(?:\s*=\s*Quantity_NOC_(\w+))?", item)
        if match is None:
            raise ValueError(f"unexpected Quantity_NameOfColor enumerator {item!r}; expected Quantity_NOC_<NAME>[ = Quantity_NOC_<NAME>]")
        if match.group(2):
            aliases.append((match.group(1), match.group(2)))
        else:
            canonical.append(match.group(1))
    return canonical, aliases


def table_file(index: int, chunk: list[tuple[str, list[str], list[str]]]) -> str:
    """One `TABLE_<index>` constant of `(name, sRGB, linear RGB)` rows."""
    rows = "".join(f'    ("{name}", [{", ".join(srgb)}], [{", ".join(rgb)}]),\n' for name, srgb, rgb in chunk)
    return f"{HEADER}\nconst TABLE_{index}: [ColorEntry; {len(chunk)}] = [\n{rows}];\n"


def constants_file(lines: list[str]) -> str:
    """One `impl NamedColor` block holding a slice of the enumerator constants."""
    return f"{HEADER}\nimpl NamedColor {{\n{''.join(lines)}}}\n"


def constant_lines(canonical: list[str], aliases: list[tuple[str, str]]) -> list[str]:
    """Doc comment plus constant for every canonical enumerator, then every alias."""
    lines = [f"    /// OCCT named color {name}; `NamedColor::{name}.name()` identifies its canonical entry.\n"
             f"    pub const {name}: Self = Self({index});\n" for index, name in enumerate(canonical)]
    lines += [f"    /// OCCT enum alias `Quantity_NOC_{alias}` of {target}; `NamedColor::{alias} == NamedColor::{target}`.\n"
              f"    pub const {alias}: Self = Self::{target};\n" for alias, target in aliases]
    return lines


def alias_file(aliases: list[tuple[str, str]]) -> str:
    """The alias spellings `Quantity_Color::ColorFromName` accepts after the table names."""
    rows = "".join(f'    ("{alias}", NamedColor::{alias}),\n' for alias, _ in aliases)
    return f"{HEADER}\nconst ALIASES: [(&str, NamedColor); {len(aliases)}] = [\n{rows}];\n"


def generate(source: Path) -> dict[Path, str]:
    """Every generated file keyed by destination path, already rustfmt-formatted."""
    entries = table_entries(source)
    canonical, aliases = enum_members(source)
    if [name for name, _, _ in entries] != canonical:
        raise ValueError("Quantity_ColorTable.pxx order differs from Quantity_NameOfColor; THE_COLORS[theName] would misindex")
    files = {OUTPUT / f"table_{i}.rs": table_file(i, entries[start:start + TABLE_CHUNK])
             for i, start in enumerate(range(0, len(entries), TABLE_CHUNK))}
    lines = constant_lines(canonical, aliases)
    files.update({OUTPUT / f"constants_{i}.rs": constants_file(lines[start:start + CONSTANT_CHUNK])
                  for i, start in enumerate(range(0, len(lines), CONSTANT_CHUNK))})
    files[OUTPUT / "aliases.rs"] = alias_file(aliases)
    return {path: rustfmt(text) for path, text in files.items()}


def rustfmt(text: str) -> str:
    """Format generated Rust exactly as `cargo fmt` would (edition 2024)."""
    result = subprocess.run(["rustfmt", "--edition", "2024", "--emit", "stdout"], input=text, text=True,
                            capture_output=True, check=True)
    return result.stdout


def main() -> None:
    """Write the generated table, or fail on any stale file with `--check`."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT / "../OCCT")
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    files = generate(options.source.resolve())
    stale = {path for path in OUTPUT.glob("*.rs")} - set(files)
    for path, text in sorted(files.items()):
        if options.check and (not path.exists() or path.read_text() != text):
            raise SystemExit(f"stale generated color table: {path}")
        if not options.check:
            path.write_text(text)
    for path in sorted(stale):
        if options.check:
            raise SystemExit(f"unexpected file in generated color table directory: {path}")
        path.unlink()


if __name__ == "__main__":
    main()
