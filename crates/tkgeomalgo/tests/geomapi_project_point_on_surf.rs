//! Direct translation of GeomAPI_ProjectPointOnSurf_Test.cxx at
//! 3d097a0328e71b826377d4814ab05ec3c3d23871. `BRepBuilderAPI_MakeEdge`,
//! `BRepBuilderAPI_MakeWire` and `BRepPrimAPI_MakePrism` (TKTopAlgo and TKPrim, not
//! ported) only carry the ellipse to the lateral face of the prism, whose surface
//! `BRep_Tool::Surface` returns; `prism_lateral_surface` is their fake: the surface
//! BRepSweep_Translation::MakeEmptyFace builds for an edge of a non-planar
//! extrusion, a Geom_SurfaceOfLinearExtrusion of a copy of the edge curve along the
//! reversed sweep direction (the face has no location).
#![allow(non_snake_case, clippy::excessive_precision)]
use rustycad_tkernel::standard::Handle;
use rustycad_tkg3d::geom::{
    GeomCurve, GeomCylindricalSurface, GeomEllipse, GeomRectangularTrimmedSurface, GeomSurface,
    GeomSurfaceOfLinearExtrusion,
};
use rustycad_tkgeomalgo::geom_api::ProjectPointOnSurf;
use rustycad_tkgeombase::extrema::{ExtAlgo, ExtFlag};
use rustycad_tkmath::gp::{self, Axis2, Direction3, Point3, Vector3};

// The fake of the prism of TKPrim: the lateral face surface of the prism of the wire
// of one edge on `curve` along `vec` (BRepSweep_Translation::MakeEmptyFace:
// `new Geom_SurfaceOfLinearExtrusion(C, D)` with `D` the reversed direction of `vec`).
fn prism_lateral_surface(curve: &Handle<dyn GeomCurve>, vec: Vector3) -> Handle<dyn GeomSurface> {
    let d = Direction3::new(vec.x(), vec.y(), vec.z())
        .unwrap()
        .reversed();
    Handle::new(GeomSurfaceOfLinearExtrusion::new(curve, d).unwrap()).cast()
}

// Bug OCC867: calling Init() with explicit UV bounds then Perform() must not throw.
// The bounds passed to Init() are intentionally tighter (U:[0,3]) than the trimmed surface
// (U:[0,4]) to reproduce the original bug scenario.
#[test]
fn GeomAPI_ProjectPointOnSurfTest__Bug867_InitWithTightBoundsNoException() {
    let aCyl: Handle<dyn GeomSurface> =
        Handle::new(GeomCylindricalSurface::new(gp::xoy().axis3(), 10.0).unwrap()).cast();
    let aTrimSurf: Handle<dyn GeomSurface> = Handle::new(
        GeomRectangularTrimmedSurface::new(&aCyl, (0.0, 4.0), (0.0, 2.0), (true, true)).unwrap(),
    )
    .cast();

    let aPoint = Point3::new(30.0, 30.0, 30.0);

    let mut aProjector = ProjectPointOnSurf::new();
    // EXPECT_NO_THROW
    let result = aProjector
        .init_surface(&aTrimSurf, (0.0, 3.0, 0.0, 2.0), ExtAlgo::Grad)
        .and_then(|()| aProjector.perform(aPoint));
    assert!(result.is_ok());
    // The original bug (OCC867) was that Init()+Perform() threw an exception.
    // Whether a projection exists within the given UV bounds is not the concern here.
}

// Migrated from tests/bugs/moddata_3/bug24138. Projecting a point onto the
// lateral face generated by an elliptical wire must return stable UV and XYZ.
#[test]
fn GeomAPI_ProjectPointOnSurfTest__OCC24138_ProjectPointOnEllipticalPrismFace() {
    let frame = Axis2::new(
        Point3::new(0.0, 0.0, 0.0),
        Direction3::new(0.0, 0.0, 1.0).unwrap(),
    )
    .unwrap();
    let anEllipse: Handle<dyn GeomCurve> =
        Handle::new(GeomEllipse::new(frame, 10.0, 5.0).unwrap()).cast();
    let aSurface = prism_lateral_surface(&anEllipse, Vector3::new(2.0, 0.0, 30.0));
    assert!(!aSurface.is_null());

    let aPoint = Point3::new(0.753071156928785, 4.98580193823337, 0.0);
    let (aUMin, aUMax, aVMin, aVMax) = aSurface.bounds();

    let mut aProjector = ProjectPointOnSurf::new();
    aProjector
        .init_surface(&aSurface, (aUMin, aUMax, aVMin, aVMax), ExtAlgo::Grad)
        .unwrap();
    aProjector.set_extrema_algo(ExtAlgo::Grad);
    aProjector.set_extrema_flag(ExtFlag::MinMax);
    aProjector.perform(aPoint).unwrap();

    assert!(aProjector.is_done());
    assert!(aProjector.nb_points().unwrap() > 0);

    let (aU, aV) = aProjector.lower_distance_parameters().unwrap();
    let aProjectedPoint = aProjector.nearest_point().unwrap();
    assert!((aProjector.lower_distance().unwrap() - 9.16061678111512e-10).abs() <= 1.0e-7);
    assert!((aU - 1.4954178490327235).abs() <= 1.0e-7);
    assert!((aV - 0.0).abs() <= 1.0e-7);
    assert!((aProjectedPoint.x() - 0.75307115689421944).abs() <= 1.0e-7);
    assert!((aProjectedPoint.y() - 4.9858019383179632).abs() <= 1.0e-7);
    assert!((aProjectedPoint.z() - 0.0).abs() <= 1.0e-7);
}
